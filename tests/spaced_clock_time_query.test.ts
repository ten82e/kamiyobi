describe("直した形がビルド成果物に残る（第 464 回）", () => {
  const 物 = readFileSync(join(builtSite(), "recommender.js"), "utf8");

  it("検索側の単位寄せに時刻の目が四つ在る – 解ける形だけ詰める", () => {
    expect(物.split(`clockTimeTermsJa(\`\${prev}\${token}\${次々}\`)`).length - 1).toBe(2);
    /* 時の語・冠の後ろが繋がれた形・分の語 – 二語で済む目は三つ、三語寄せる目は二つ */
    expect(物.split(`clockTimeTermsJa(\`\${prev}\${token}\`)`).length - 1).toBe(3);
    expect(物.split("/^[時]/.test(token)").length - 1).toBe(2);
    expect(物.split("/^[分]/.test(次々)").length - 1).toBe(1);
    expect(物.split("/^[0-9]{1,2}時(?:[0-9]{1,2}分|半)?$/").length - 1).toBe(2);
  });
  it("案内側にも同じ四つの目がある – 解くのは寄せた形、名乗りは打たれた侭", () => {
    expect(物.split(`clockTimeTermsJa(\`\${前.解}\${token}\${次}\`)`).length - 1).toBe(2);
    expect(物.split(`clockTimeTermsJa(\`\${前.解}\${token}\`)`).length - 1).toBe(3);
    expect(物.split("clockTimeTermsJa(解 || token)").length - 1).toBe(1);
    /* 三語をまとめて飛ばす目は第 466 回の数値の相対日にも有るので、其れごと數える
     * （宣言 1・読み 1・戻し 1・`true` を立てる所 3 – 実測で張る）。*/
    expect(物.split("次を飛ばす").length - 1).toBe(6);
    expect(物.split("次を飛ばす = true").length - 1).toBe(3);
  });
  it("語の表の目に時刻の境界が増えた", () => {
    expect(物.split("clockTimeTermsJa(語) !== null").length - 1).toBe(1);
    expect(物.match(/幅の語尾を継いだ形が解けるJa\(/g)?.length).toBe(3);
  });
  it("幅の語尾の表に測つて解ける語尾だけ – `から` `より` `前` を足し `いっぱい` `この先` は载せない", () => {
    const 宣言 = 物.match(/const 幅の語尾の語Ja = [\s\S]{0,220}?;/g) ?? [];
    expect(宣言.length).toBe(1);
    for (const 語尾 of [
      "(?:までに|まで",
      "|中に|中",
      "|以内",
      "|以降|以後|以来",
      "|前に|前",
      "|より|から",
    ]) {
      expect(宣言[0], 語尾).toContain(語尾);
    }
    for (const 語尾 of ["|いっぱい", "|この先"]) {
      expect(宣言[0], 語尾).not.toContain(語尾);
    }
  });
});
