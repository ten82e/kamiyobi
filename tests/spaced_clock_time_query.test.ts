describe("件数欄は打たれた空格の侭を名乗り、別な帯を書かない（第 464 回）", () => {
  it("時刻の語尾を離つた形は、其の範囲を打たれた侭の名前で書く", () => {
    const 文 = Recommender.relativeDayNotes("17 時 以降", 基準);
    expect(文.length).toBe(1);
    expect(文[0].startsWith("17 時 以降 = 17:00〜23:59（17時以降） の締切")).toBe(true);
    expect(Recommender.relativeDayNotes("正午 以降", 基準)[0]).toContain(
      "正午 以降 = 12:00〜23:59（正午以降）",
    );
  });
  it("冠を離つた形は冠の帯だけを書かない – 其の時刻からの帯を書く", () => {
    const 文 = Recommender.relativeDayNotes("午後 5 時 以降", 基準);
    expect(文[0].startsWith("午後 5 時 以降 = 17:00〜23:59（午後5時以降）")).toBe(true);
    expect(文[0]).not.toMatch(/^午後 = /);
  });
  it("分を離つた形も其の分からの帯を書く", () => {
    expect(
      Recommender.relativeDayNotes("9 時 30 分 以降", 基準)[0].startsWith(
        "9 時 30 分 以降 = 09:30〜23:59（9時30分以降）",
      ),
    ).toBe(true);
    expect(
      Recommender.relativeDayNotes("23 時 59 分 以降", 基準)[0].startsWith(
        "23 時 59 分 以降 = 23:59〜23:59（23時59分以降）",
      ),
    ).toBe(true);
  });
  it("単位だけを離した形は其の時分の幅を書く（詰め形と同じ解き方）", () => {
    expect(Recommender.relativeDayNotes("17 時", 基準)[0]).toContain("17 時 = 17:00〜17:59");
    expect(Recommender.relativeDayNotes("9 時", 基準)[0]).toContain("9 時 = 09:00〜09:59");
  });
  it("解けた形の件数欄は範囲を書き、打ち直しの導きを出さない（第 447 回の見張り）", () => {
    const 文 = JSON.stringify(Recommender.relativeDayNotes("17 時 以降", 基準));
    expect(文).toContain("17:00〜23:59");
    expect(文).not.toContain("繋げて打ってください");
    /* 導きは 0 件の時だけ画面に出る見張りに通る（`site/app.ts`）。解けた形（181 件）は
     * その門を通らないので、行が出るのに「絞り込めません」は届かない（第 447 回）。*/
    expect(列("17 時 以降").size).toBeGreaterThan(0);
  });
  it("語尾だけの打ち方は其の侭打ち直しの導きが出る（第 447 回 – 起点が本当に無い形）", () => {
    expect(String(Recommender.uiWordNoteJa("以降"))).toContain("繋げて打ってください");
    expect(列("以降").size).toBe(0);
  });
});

