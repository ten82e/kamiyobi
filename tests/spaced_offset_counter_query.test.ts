/**
 * 数値の相対日（`1か月後` `2か月前` `1年後` `半月後`）の数と単位を空格で離って打つ形（第 466 回）。
 *
 * 実測（2026-11-07 – 実ビルドの品書 872 行・固定時刻 2026-08-09T00:00:00Z）で、詰め形は通るのに
 * 数を離しただけで黙つて居た – `1か月後` 18 行 / `1 か月後` **0 行**・`1 か月 後` **0 行**・
 * `1か月 後` **0 行**・`1か月前` 7 行 / `1 か月前` **0 行**・`1年後` 2 行 / `1 年後` **0 行**・
 * `1年前` 2 行 / `1 年前` **0 行**・`3か月後まで` 577 行 / `3 か月後 まで` **0 行**・
 * `一か月後` 18 行 / `一 か月後` **0 行**・`半月後` 8 行 / `半月 後` **0 行**。
 * IME は数字と漢字の間に空格を入れやすいので、研究者が「1 か月後の締切」と打つのは自然な打ち方。
 *
 * 直し – 検索の語を割る段（`単位を数字に寄せるJa`）に、寄せた形を数値の相対日の形の表
 * （`数値の相対日の形Ja`）で確かめてから詰める目を三つ（二語・単位だけの語を挟む三語・単位まで
 * 済んだ語の後ろに `後` `前`）。**寄せた形が其の方の表に載る時だけ**寄せる決まりは第 453 回
 * その侭なので、其の方の表が持たない `1 か月`（単位だけ）と `1 時間` `30 分` は寄せない。
 * 漢数字（`一 か月後`）は其の方の機械が算用数字の一語を見るので、寄せた形で第 392 回の漢数字の
 * 寄せを通してから表を見る。
 *
 * 件数欄は検索側と同じ三つの目を別に持つ – 解くのは寄せた形、名乗りは打たれた侭（第 332 回・
 * 第 462 回）。此の頁の検査は同じ検査の品書（435 行）で測つた数を持つ（第 442 回）。
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { FILTER_RUNTIME_STUBS } from "./built_golden_shared.ts";
import { builtSite } from "./built_site.ts";

const 基準 = Date.parse("2026-08-09T00:00:00Z");

/* 品の語は `candidateRows` が作った検索の語（`hay`）の文字列 – 照合は其の文字列に掛かる。*/
function 品書(): string[] {
  return (
    Recommender.candidateRows(
      JSON.parse(readFileSync(join(builtSite(), "catalog.json"), "utf8")) as unknown as never,
    ) as unknown as Array<{ hay: string }>
  ).map((行) => String(行.hay));
}

const 全 = 品書();

function 列(query: string): Set<string> {
  const 当 = Recommender.searchMatcher(query, 基準);
  return new Set(全.filter((行) => 当(行) === true));
}

function 対称差(x: Set<string>, y: Set<string>): number {
  let 差 = 0;
  const 向 = new Set(y);
  for (const 物 of x) if (!向.has(物)) 差 += 1;
  const 帰 = new Set(x);
  for (const 物 of y) if (!帰.has(物)) 差 += 1;
  return 差;
}

describe("数と単位を離って打っても数値の相対日は詰め形と同じ行に出る（第 466 回）", () => {
  const 対: Array<[string, string, number]> = [
    ["1 か月後", "1か月後", 4],
    ["1 か月 後", "1か月後", 4],
    ["1か月 後", "1か月後", 4],
    ["2 か月後", "2か月後", 6],
    ["3 か月後", "3か月後", 4],
    ["3 か月後 まで", "3か月後まで", 366],
    ["1 か月後 の締切", "1か月後の締切", 3],
    ["1 か月後 まで", "1か月後まで", 161],
    /* 幅の語尾をもう一つ離った形 – 案内側が三語を飛ばさないと、此處の案内が一日分の
     * 日付になって噓を書く（下の「件数欄」の張りで見る）。*/
    ["1 か月 後 まで", "1か月後まで", 161],
    ["3 か月 後 まで", "3か月後まで", 366],
    ["半月 後 まで", "半月後まで", 65],
    ["1 か月後 です", "1か月後です", 4],
    /* 漢数字 – 詰め形 `一か月後` 18 行（実ビルド）は其の方の漢数字の寄せで通る（第 392 回）。*/
    ["一 か月後", "一か月後", 4],
    ["一 か月 後", "一か月後", 4],
    /* `半` – 其の方の表が字の侭持つ語（`半月後` 8 行 – 第 426 回）。*/
    ["半月 後", "半月後", 4],
    ["半 か月後", "半か月後", 4],
    ["半 月 後", "半月後", 4],
    /* 第 462 回で既に開いて居た週と日 – 同じ目をくぐつても壊れて居ない事。*/
    ["2週間 後", "2週間後", 1],
    ["2 週間 後", "2週間後", 1],
  ];
  for (const [空格, 詰め, 期待] of 対) {
    it(`「${空格}」は詰め形「${詰め}」と同じ ${期待} 行`, () => {
      /* 詰め形が其の方の品で一行以上引ける事 – 両側 0 行の空振りで対称差 0 を通さない。*/
      expect(列(詰め).size, 詰め).toBe(期待);
      expect(対称差(列(空格), 列(詰め)), `${空格} ⇔ ${詰め}`).toBe(0);
    });
  }

  it("向こう側（`前`）と年単位も同じ – この品書では詰め形も 0 行なので 0 行の対称で見る", () => {
    /* 実ビルド（872 行）では `1 か月前` 0 行 → 7 行・`1 年後` 0 行 → 2 行・`1 年前` 0 行 → 2 行に
     * 直つた（件の無い品書では 0 行のまま – 対称差 0 と、詰め形も 0 行であることを張る）。*/
    for (const [空格, 詰め] of [
      ["1 か月前", "1か月前"],
      ["2 か月前", "2か月前"],
      ["1 か月 前", "1か月前"],
      ["1か月 前", "1か月前"],
      ["二 か月前", "二か月前"],
      ["1 年後", "1年後"],
      ["2 年後", "2年後"],
      ["1 年 後", "1年後"],
      ["1 年前", "1年前"],
      ["10 か月後", "10か月後"],
      ["10 日 後", "10日後"],
      ["3 か月後 から", "3か月後から"],
    ] as Array<[string, string]>) {
      expect(列(詰め).size, 詰め).toBe(0);
      expect(対称差(列(空格), 列(詰め)), `${空格} ⇔ ${詰め}`).toBe(0);
    }
  });
});

describe("其の方の機械が解かない単位は寄せない（第 453 回）", () => {
  const 不動: Array<[string, number]> = [
    /* 時間・分は数値の相対日の表に無い – 第 464 回で時刻の機械側を直したので、ここで
     * 詰めると別の語に化ける（`2 時間後` は詰め形も 0 行）。*/
    ["2 時間後", 0],
    ["2時間後", 0],
    ["1 時間後", 0],
    ["1 時間", 0],
    ["5 分 後", 0],
    ["30 分", 0],
    /* 単位だけの形（`1 か月`）は其の方の表に無い – 実ビルドでは案内が「暦のか月の幅で絞る欄が
     * 無い」と書く打ち方で、詰め形 `1か月` も 0 行なので寄せない。*/
    ["1 か月", 0],
    ["1か月", 0],
    ["1 か月 以内", 0],
    ["1か月以内", 0],
    ["一か月以内", 0],
    ["1 か月 と 2 か月", 0],
    ["1 か月半", 0],
    ["ml か月", 0],
    ["論文 か月", 0],
    /* 語のかけ算で別の幅になる語は寄せない侭（下表の「残した差」）。*/
    ["1 年前の締切", 0],
  ];
  for (const [打ち方, 期待] of 不動) {
    it(`「${打ち方}」は今まで通り ${期待} 行`, () => {
      expect(列(打ち方).size, 打ち方).toBe(期待);
    });
  }

  it("『半年 後』は寄せない – 詰め形 `半年後` は範囲の欄が受ける語で、寄せると行が減る", () => {
    /* 実測（実ビルド 872 行）で `半年 後` 21 行 / `半年後` 9 行 – 詰め形は半年専用の範囲の決まりが
     * 受けるので、空格形をそこに寄せると語のかけ算で出て居た行が減る（第 453 回 – 減らす直しは
     * 別の決まりが必要）。この品の数で張つて、寄せる直しがされた時に落ちるようにする。*/
    expect(列("半年 後").size).toBe(16);
    expect(列("半年後").size).toBe(2);
    expect(対称差(列("半年 後"), 列("半年後"))).toBeGreaterThan(0);
  });
});

describe("件数欄は寄せた形で解き、名乗りは打たれた侭にする（第 332 回・第 466 回）", () => {
  const 名乗り: Array<[string, string]> = [
    ["1 か月後", "1 か月後 = 2026年9月9日(水)"],
    ["1 か月 後", "1 か月 後 = 2026年9月9日(水)"],
    ["1か月 後", "1か月 後 = 2026年9月9日(水)"],
    ["一 か月後", "一 か月後 = 2026年9月9日(水)"],
    ["半月 後", "半月 後 = 2026年8月24日(月)"],
    ["1 年後", "1 年後 = 2027年8月9日(月)"],
    ["3 か月後 まで", "3 か月後 まで = 2026年8月9日(日)〜11月9日(月)の締切"],
  ];
  for (const [打ち方, 期待] of 名乗り) {
    it(`「${打ち方}」の件数欄は「${期待}」`, () => {
      const 案内 = Recommender.relativeDayNotes(打ち方, 基準).join("");
      expect(案内).toContain(期待);
      /* 行は其の日に絞れて居る – 「絞り込まずにいます」は噓なので出してはいけない。*/
      expect(案内).not.toContain("絞り込まずにいます");
    });
  }

  it("`まで` を離って打った形の案内は範囲を書く – 一日分の日付を書いたら噓", () => {
    /* 改ざんで実測（第 466 回）– 案内側で三語を飛ばす決まりを消すと、行は 161 行の侭、
     * 案内だけ「1 か月 後 = 2026年9月9日(水)」の一日分になつた（幅の語尾 `まで` が別の語として
     * 処理される為）。案内は画面に出る物なので、行と食い違へば噓（第 332 回）。*/
    expect(Recommender.relativeDayNotes("1 か月 後 まで", 基準).join("")).toContain(
      "1 か月 後 まで = 2026年8月9日(日)〜9月9日(水)の締切",
    );
    expect(Recommender.relativeDayNotes("3 か月 後 まで", 基準).join("")).toContain(
      "3 か月 後 まで = 2026年8月9日(日)〜11月9日(月)の締切",
    );
    expect(列("1 か月 後 まで").size).toBe(161);
  });

  it("単位だけの打ち方は案内を黙らせる – 行が出ないのと揃つて居る", () => {
    /* `1 か月` は詰め形 `1か月` と同じ 0 行（実測）なので、黙つて居るのは噓では無い（第 332 回）。
     * 詰め形の方だけ「暦のか月の幅で絞る欄が無い」と書くのは残した差 – §7 に記す。*/
    expect(Recommender.relativeDayNotes("1 か月", 基準), "1 か月").toEqual([]);
    expect(列("1 か月").size).toBe(0);
  });
});

