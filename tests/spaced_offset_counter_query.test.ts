describe("直した形がビルド成果物に残る（第 466 回）", () => {
  const 物 = readFileSync(join(builtSite(), "recommender.js"), "utf8");

  it("寄せ形の手順は一箇所で、検索側と案内側が同じ六つの目を通る", () => {
    expect(物.split("function 相対日の寄せ形Ja(前, 語, 語尾) {").length - 1).toBe(1);
    /* 手順の定義 1 + 呼び出し 4（検索側 2・案内側 2）。目を一本でも増やせば此處が動く。*/
    expect(物.split("相対日の寄せ形Ja(").length - 1).toBe(5);
    /* 検索側 – ① 数 + 単位付き語、② 数 + 単位だけの語 + `後` `前` の三語。*/
    expect(物.split('相対日の寄せ形Ja(prev, token, "")').length - 1).toBe(1);
    expect(物.split("相対日の寄せ形Ja(prev, token, 次々)").length - 1).toBe(1);
    /* 案内側 – 同じ二つの目（解くのは寄せた形、名乗りは打たれた侭）。*/
    expect(物.split('相対日の寄せ形Ja(前 ? 前.解 : "", token, "")').length - 1).toBe(1);
    expect(物.split("相対日の寄せ形Ja(前.解, token, 次)").length - 1).toBe(1);
    /* 単位まで済んだ語の後ろに `後` `前` を離って付ける形は、語を割る前の文字列の書換が既に
     * 詰めて居るので目を置いていない（実測 – 其の目を無効化しても `1か月 後` 18 行で一字も
     * 変わらなかつた）。第 463 回 – 使はれない目は置かないので、置かれて居ない事も張る。*/
    expect(物.split('相対日の寄せ形Ja(前.解, token, "")').length - 1).toBe(0);
    expect(物.split('相対日の寄せ形Ja(prev, token, "")').length - 1).toBe(1);
    /* 表で確かめてから寄せる – 其の方の形の表を呼んでいない目を作つたら落ちる。*/
    expect(物.split("数値の相対日の形Ja.test(詰)").length - 1).toBe(1);
    expect(物.split("/^(?:[0-9]+|[〇一二三四五六七八九十]{1,3}|半)$/").length - 1).toBe(2);
    expect(物.split("/^(?:か月|カ月|ヵ月|ヶ月|ケ月|箇月|年|日|月)$/").length - 1).toBe(2);
  });

  it("検査の注入（`new Function` のハーネス）も同じ手順を持つ – 本番だけ通っても直つた事にはならない", () => {
    /* 第 466 回の実発生 – 検索の語を割る段が新しい手順を呼ぶようにした時、ビルド成果物だけの
     * 検査は通り、`jsFunction` で関数を抜き出して `node -e` に流し込むハーネスだけが
     * `ReferenceError: 相対日の寄せ形Ja is not defined` で落ちた。注入一覧が本体の写しであることを
     * ここで張る（抜き忘れは画面の直しにならない – 第 244 回と同じ決まり）。*/
    expect(FILTER_RUNTIME_STUBS).toContain("function 相対日の寄せ形Ja(前, 語, 語尾)");
    expect(FILTER_RUNTIME_STUBS).toContain("function 幅の漢数字を寄せるJa(");
  });
});
