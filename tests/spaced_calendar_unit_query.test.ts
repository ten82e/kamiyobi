import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { builtSite } from "./built_site.ts";

const 基準 = Date.parse("2026-08-09T00:00:00Z");

function 品書(): string[] {
  return (
    Recommender.candidateRows(
      JSON.parse(readFileSync(join(builtSite(), "catalog.json"), "utf8")) as unknown as never,
    ) as unknown as Array<{ hay: string }>
  ).map((行) => String(行.hay));
}

function 対称差(x: Set<string>, y: Set<string>): number {
  let n = 0;
  for (const a of x) if (!y.has(a)) n += 1;
  for (const b of y) if (!x.has(b)) n += 1;
  return n;
}

describe("空格で離した暦日の単位と境界の語が詰め形と同じ行に出る（第 456 回）", () => {
  const 品 = 品書();
  const 列 = (q: string): Set<string> => {
    const 当 = Recommender.searchMatcher(q, 基準);
    return new Set(品.filter((行) => 当(行) === true));
  };

  const 組: Array<[string, string, number]> = [
    ["8 月", "8月", 118],
    ["1 月", "1月", 23],
    ["10 月", "10月", 97],
    ["8 月 22 日", "8月22日", 4],
    ["2 月 3 日", "2月3日", 6],
    ["1 月 1 日", "1月1日", 6],
    ["8 月 8 日", "8月8日", 1],
    ["3 月 31 日", "3月31日", 3],
    ["2026 年", "2026年", 427],
    ["2026 年 8 月", "2026年8月", 118],
    ["2026 年 8 月 22 日", "2026年8月22日", 4],
    ["8 月 22 日以降", "8月22日以降", 414],
    ["1 月 1 日 以降", "1月1日以降", 114],
    ["6 月 1 日 以降", "6月1日以降", 5],
    ["2 月 14 日 から", "2月14日から", 94],
    ["7 月 1 日 から", "7月1日から", 3],
    ["12 月 31 日 まで", "12月31日まで", 423],
    ["1 月 1 日 までに", "1月1日までに", 423],
    ["12 月 31 日 までに", "12月31日までに", 423],
    ["12 月 24 日 までに", "12月24日までに", 421],
    ["8 月 22 日 までに", "8月22日までに", 60],
    ["2026 年 8 月 22 日 までに", "2026年8月22日までに", 60],
    ["2026 年 2 月 14 日 から", "2026年2月14日から", 427],
    ["2 月 3 日 から", "2月3日から", 97],
    ["8 月下旬", "8月下旬", 58],
  ];
  for (const [空, 詰, 期待] of 組) {
    it(`「${空}」は詰め形「${詰}」と一字も違わない（${期待} 行）`, () => {
      const 実 = 列(詰);
      /* 詰め形がその方の品で一行以上引ける事 – 両側 0 行の空振りで対称差 0 が
       * 通る穴を防ぐ。 */
      expect(実.size, 詰).toBeGreaterThan(0);
      expect(実.size, 詰).toBe(期待);
      expect(対称差(列(空), 実), 空).toBe(0);
    });
  }

  /* 助詞を挟む打ち方は第 455 回が既に受ける – 漢字の暦日でも同じ（門が落ちない事）。 */
  it("助詞を挟む打ち方も詰め形と同じ", () => {
    expect(対称差(列("12/31 の までに"), 列("12/31までに"))).toBe(0);
    expect(列("12/31までに").size).toBe(423);
    /* 漢字で書く暦日でも同じ – 門が前語（の前の語）を見る迄寄せる。 */
    expect(対称差(列("12 月 24 日 の までに"), 列("12月24日までに"))).toBe(0);
    expect(列("12月24日までに").size).toBe(421);
  });

  const 在ら無い日: Array<[string, number]> = [
    ["4 月 31 日", 0],
    ["2 月 30 日", 0],
    ["2 月 29 日", 0],
    ["9 月 31 日 まで", 0],
    ["2 月 29 日 まで", 0],
  ];
  for (const [打ち方, 期待] of 在ら無い日) {
    it(`在ら無い日「${打ち方}」は今まで通り ${期待} 行`, () => {
      expect(列(打ち方).size, 打ち方).toBe(期待);
    });
  }

  /* 別々の月を並べた物は寄せない（`8 月 9 月` は 8 月 且つ 9 月の行 – 詰め形
   * `8月9月` の月の列とは違う）。 */
  it("別々の月を並べた打ち月は寄せない", () => {
    expect(列("8 月 9 月").size).toBe(13);
    expect(対称差(列("8 月 9 月"), 列("8月9月"))).toBeGreaterThan(0);
  });

  /* 不動 – 帯・相対日・幅の語は暦日の語では無いので寄せない。 */
  const 不動: Array<[string, number]> = [
    /* 帯（`17 時 以降` `正午 以降`）は第 464 回でその方の機械が解くやうにしたので、
     * この表から降ろして別の検査で張る。ゾーンと幅の語はその侭寄せない。*/
    ["JST 以降", 0],
    ["5 日間", 0],
    ["2/30 以降", 0],
    /* 幅の語尾を離って打つ形は第 462 回で詰め形と同じ行に出る（この表の 0 行は古い決まり）。*/
    ["来週 まで", 43],
    ["明日 まで", 2],
    ["2026 年 8 月 22 日 17 時", 0],
    /* 助詞で割れる形はその方の決まり（`3 日前` は詰め形とも同じ 1 行）。 */
    ["3 日前", 1],
    /* 月の語単独・帯の語の不動。 */
    ["17時以降", 181],
    ["第 2 ラウンド", 16],
    ["月 曜", 436],
  ];
  for (const [打ち方, 期待] of 不動) {
    it(`「${打ち方}」は今まで通り ${期待} 行`, () => {
      expect(列(打ち方).size, 打ち方).toBe(期待);
    });
  }

  /* 単位の語を離つた打ち月 – 第 456 回当時は 0 行で、第 464 回で詰め形と同じ行に出る。 */
  const 解けた: Array<[string, string, number]> = [
    ["17 時 以降", "17時以降", 181],
    ["17時 以降", "17時以降", 181],
    ["正午 以降", "正午以降", 191],
    ["23 時 59 分", "23時59分", 181],
  ];
  for (const [空格, 詰め, 期待] of 解けた) {
    it(`「${空格}」は詰め形「${詰め}」と同じ ${期待} 行（第 464 回）`, () => {
      expect(列(詰め).size, 詰め).toBe(期待);
      expect(対称差(列(空格), 列(詰め)), 空格).toBe(0);
    });
  }
});

describe("直した形がビルド成果物に残る（第 456 回）", () => {
  const 物 = readFileSync(join(builtSite(), "recommender.js"), "utf8");
  it("単位寄せの定義が 1 箇所・語の割りの内側の呼びが 1 箇所", () => {
    expect(物.split("function 単位を数字に寄せるJa(").length - 1).toBe(1);
    expect(
      物.split(
        "範囲の語を寄せるJa(暦日を境界に寄せるJa(mergeSeasonTokens(単位を数字に寄せるJa(queryTokens(query, now))), now), now)",
      ).length - 1,
    ).toBe(1);
  });
  it("同じ数字の語を重複として落とさない目が 1 箇所", () => {
    /* ビルドの整形は `seen.push(part)` を別行に落とす – 条件の目印までを張る。 */
    expect(物.split("if (seen.indexOf(part) < 0 || 並べるか)").length - 1).toBe(1);
    /* 第 457 回で助詞の向こう側の重複も落とさない目が増え、ビルドの整形で条件が
     * 複数行に折られた – 目印は先頭の二片だけ張る（行数は別の検査で張る）。 */
    expect(
      物.split("const 並べるか = /^[0-9]+$/.test(前) ||\n                /^[年月日]$/.test(前)")
        .length - 1,
    ).toBe(1);
  });
  it("暦日のかたまりを繋ぐ目（年・月・日の詰めた形）が 1 箇所", () => {
    expect(
      物.split("/^(?:[0-9]{4}年[0-9]{1,2}月(?:[0-9]{1,2}日)?|[0-9]{1,2}月[0-9]{1,2}日)$/.test(")
        .length - 1,
    ).toBe(1);
  });
  it("裸の境界の語を暦日へ寄せる決まりがその日を解く目を通る（在らない日を寄せない）", () => {
    /* 目だけで決まる守り – 改ざんで素通しにしてもその方の目が在ら無い日を解かない
     * ので行に差が出ないなので字面で張る。 */
    expect(物.split("暦日に解くJa(prev) !== null").length - 1).toBe(1);
    expect(物.split("暦日に解くJa(詰) !== null").length - 1).toBe(1);
  });
  it("裸の境界の語を暦日へ寄せる決まりが 1 箇所", () => {
    expect(
      物.split('if (prev && 芯 === "" && 語尾 !== "" && 境界の語尾Ja(語尾) && 暦日の語かJa(prev))')
        .length - 1,
    ).toBe(1);
  });
});
