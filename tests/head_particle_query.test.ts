/* 第 461 回 – 助詞を**後ろの語に繋げて**打つ人が、其の語だけで打つ人と同じ行に
 * 届くようにした（`論文 の締切` `ml の会議` `8月 の締切` `ml で締切` 等）。
 * 実測（2026-11-05 – 実ビルドの品書 872 行・固定時刻 2026-08-09T00:00:00Z）:
 * 助詞を前后に空格で立てる打ち方（第 458 回）と語の末尾に繋げる打ち方（第 459 回）は
 * 通るのに、助詞を後ろの語に繋げただけで 0 行だつた –
 * `論文 の 締切` 461 行 / `論文 の締切` **0 行**・`ml の 会議` 99 行 / `ml の会議` **0 行**・
 * `8 月 の 締切` 189 行 / `8月 の締切` **0 行**・`来週 の 締切` 50 行 / `来週 の締切` **0 行**・
 * `国内 の 会議` 38 行 / `国内 の会議` **0 行**・`HPC の 会議` 108 行 / `HPC の会議` **0 行**・
 * `ai の 学会` 2 行 / `ai の学会` **0 行**・`ml で 締切` 67 行 / `ml で締切` **0 行**・
 * `ai が 学会` 2 行 / `ai が学会` **0 行**。助詞だけの語を落とす目（第 458 回）は、其の方の語が
 * 割れ無いと掛からない為。実測値を張るのは検査用ビルドの品書（tests/built_site.ts – 435 行）–
 * 実ビルド（872 行）とは行数が違うので、詰め形・完全空格形との対称差 0 と共に、其の方で
 * 測つた行数を張る（第 455 回の流儀）。 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { builtSite } from "./built_site.ts";

const 基準 = Date.parse("2026-08-09T00:00:00Z");
const 品 = (
  Recommender.candidateRows(
    JSON.parse(readFileSync(join(builtSite(), "catalog.json"), "utf8")) as unknown as never,
  ) as unknown as Array<{ hay: string }>
).map((行) => String(行.hay));

function 列(語: string): Set<string> {
  return new Set(品.filter((行) => Recommender.searchMatcher(語, 基準)(行) === true));
}

function 対称差(a: Set<string>, b: Set<string>): number {
  return [...a].filter((k) => !b.has(k)).length + [...b].filter((k) => !a.has(k)).length;
}

describe("助詞を後ろの語に繋げた打ち方が他の打ち方と同じ行に出る（第 461 回）", () => {
  /* [助詞を後ろに繋げた形, 詰め形, 完全空格形, 検査用ビルドで測つた行数] */
  const 形: Array<[string, string, string, number]> = [
    ["論文 の締切", "論文の締切", "論文 の 締切", 264],
    ["ml の会議", "mlの会議", "ml の 会議", 18],
    ["8月 の締切", "8月の締切", "8 月 の 締切", 114],
    ["来週 の締切", "来週の締切", "来週 の 締切", 43],
    ["国内 の会議", "国内の会議", "国内 の 会議", 38],
    ["ai の学会", "aiの学会", "ai の 学会", 2],
    ["ai が学会", "aiが学会", "ai が 学会", 2],
    ["HPC の会議", "HPCの会議", "HPC の 会議", 87],
    ["セキュリティ の会議", "セキュリティの会議", "セキュリティ の 会議", 68],
    ["ml で締切", "mlで締切", "ml で 締切", 14],
  ];

  for (const [繋げた形, 詰め形, 完全空格, 期待] of 形) {
    it(`「${繋げた形}」は詰め形・完全空格形と同じ ${期待} 行`, () => {
      const 繋 = 列(繋げた形);
      const 詰 = 列(詰め形);
      const 全 = 列(完全空格);
      expect(対称差(繋, 詰), `対称差が出た: ${繋げた形} ⇔ ${詰め形}`).toBe(0);
      expect(対称差(繋, 全), `対称差が出た: ${繋げた形} ⇔ ${完全空格}`).toBe(0);
      /* 実質の行を引いて居る事（空振りの対称差 0 を防ぐ – 第 455 回）。 */
      expect(詰.size, `詰め形が ${期待} 行で無い: ${詰め形}`).toBe(期待);
      expect(繋.size, `繋げた形が ${期待} 行で無い: ${繋げた形}`).toBe(期待);
    });
  }

  it("助詞を二つ離つて打つ形も同じ（月を離つた打ち方）", () => {
    expect(対称差(列("8 月 の締切"), 列("8月 の締切"))).toBe(0);
    expect(対称差(列("8 月 の締切"), 列("8 月 の 締切"))).toBe(0);
    expect(列("8 月 の締切").size).toBe(114);
  });

  it("広げた事は件数欄におしらせが出る（黙つて語を増やさない）", () => {
    const おしらせ = Recommender.querySynonymNotes("来週 の締切").join(" ");
    expect(おしらせ).toContain("「の締切」は「来週」と「締切」に分けて");
    /* 相対日の語は其の範囲を其の侭名乗る（第 332 回）。 */
    expect(Recommender.relativeDayNotes("来週 の締切", 基準).join(" ")).toContain(
      "来週 = 2026年8月10日(月)〜8月16日(日)",
    );
  });
});

describe("剥がないと決めた形（測つた断り）", () => {
  it("助詞だけで立つ語は第 458 回の侭（語その物を打った人の当たりを変へない）", () => {
    /* 前に語が在る時だけ剥ぐ – 語の頭で立つ助詞は其侭残る。 */
    expect(列("の").size).toBe(175);
    expect(列("の 締切").size).toBe(151);
    expect(列("ml で").size).toBe(18);
    /* 前に語が無いので剥がない – 助詞が前に付いた打ち方も 0 行の侭（寄せない）。 */
    expect(列("の締切").size).toBe(0);
    expect(列("で締切").size).toBe(0);
  });

  it("平仮名だけの語と一文字で了う語は剥がない（第 417 回・第 419 回）", () => {
    /* 『しまね』は島根の行が出る語 – 頭の字を剥いだ『まね』にしない。 */
    expect(列("しまね").size).toBe(1);
    expect(対称差(列("ことです"), 列("です"))).toBe(0);
  });

  it("並べた語の助詞 `と` は語頭に付けない（第 457 回の列挙を壊さない）", () => {
    /* 実測 – 詰め形 441 行 / 完全空格形 441 行。`と` を語頭の助詞に入れると語の組が
     * 積に割れて此の形が化けるので、表に入れて居ない。 */
    expect(対称差(列("8 月 と 9 月"), 列("8月と9月"))).toBe(0);
    expect(列("8月と9月").size).toBe(284);
    expect(列("と締切").size).toBe(0);
  });

  it("第 459 回の語尾の助詞・第 460 回の冠・第 458 回の空格は其侭通る", () => {
    for (const [空格, 詰め] of [
      ["機械学習で", "機械学習"],
      ["mlで", "ml"],
      ["aiに", "ai"],
      ["第 2 週", "第2週"],
      ["8 月 第 2 週", "8月第2週"],
      ["論文 の 締切", "論文の締切"],
      ["来週 の 締切", "来週の締切"],
      ["12 月 31 日 まで", "12月31日まで"],
    ] as Array<[string, string]>) {
      expect(対称差(列(空格), 列(詰め)), `対称差が出た: ${空格} ⇔ ${詰め}`).toBe(0);
    }
    expect(列("12月31日まで").size).toBe(422);
    expect(列("第2週").size).toBe(26);
  });
});

describe("直した形がビルド成果物に残る（第 461 回）", () => {
  const 物 = readFileSync(join(builtSite(), "recommender.js"), "utf8");

  it("語頭の助詞の表が 1 箇所（`と` を入れて居ない – 第 457 回）", () => {
    const 一行 = 物.split("\n").filter((行) => 行.includes("const 語頭の助詞Ja ="));
    expect(一行.length).toBe(1);
    expect(一行[0]).toContain("^(?:で|に|は|が|も|の|や)");
    expect(一行[0]).not.toContain("|と");
    /* 一文字の終助詞は入れて居ない（第 417 回）。 */
    for (const 字 of ["か", "な", "よ", "ね"]) expect(一行[0]).not.toContain(`|${字}`);
  });

  it("前に語が在る時だけ剥ぐ・一文字にしない・平仮名だけの語を剥がない守りが在る", () => {
    expect(物.split("打たれた語々.slice(0, 番).some(").length - 1).toBe(1);
    expect(物.split("頭を剥いだ.length >= 2").length - 1).toBe(1);
    expect(物.split("頭を剥いだ !== 文").length - 1).toBe(1);
    /* 平仮名だけの語を守る目は、格助詞を剥ぐ目（第 419 回）・語尾の助詞を剥ぐ目
     * （第 459 回）・語頭の助詞を剥ぐ目（第 461 回）・限定の助詞を剥ぐ目（第 657 回）の
     * 四箇所で働く。今日の品書では語頭の形で行の数が出無い（『やまぐち』『ものづくり』は
     * いずれも 0 行）ので挙動では見張れ無い – 仮名の都市名・主題語の表は増えて行く物なので、
     * 壊れた時の差が見えないまま置くのは危ない為、字面で見張る。
     * 第 657 回で四つ目に增えたのは「`しまねのみ` を『まねのみ』に壞さん」為 – 檢査
     * `tests/restrictive_particle_query.test.ts` が其の形その物で張つて居る。*/
    /* 五つ – 格の助詞の他に、限定の助詞（第 657 回）・語の間に繋げた限定の助詞（第 658 回）・
     * 限定の語名（第 659 回）の剥ぐ番が同じ假名だけの守りを見る（割る番は別段）。 */
    expect(物.split("平仮名だけJa.test(文)").length - 1).toBe(5);
  });
});
