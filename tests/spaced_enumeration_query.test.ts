/* 第 457 回 – 並べた語（列挙）を助詞の前後で空格で離って打つ人が、詰めて打つ人と
 * 同じ行に届くようにした（`8 月と 9 月` `8 月 と 9 月` `12 月 と 1 月`
 * `8 月 10 日 と 8 月 20 日` `2026 年 8 月 と 2026 年 9 月` 等）。
 * 実測（2026-11-05 – 実ビルドの品書 872 行・固定時刻 2026-08-09T00:00:00Z）:
 * 詰め形は通る（`8月と9月` 441 行・`12月と1月` 290 行・`8月10日と8月20日` 17 行・
 * `8月10日と11日` 7 行・`8月と9月と10月` 588 行・`8月または9月` 441 行）のに、
 * 助詞を離しただけの打ち方は 0 行・2 行・3 行・1 行に化けて居た。原因は三つ –
 * (1) 空格で打たれた `と` が第 419 回の格助詞剥がしで落ち、語の組が **積** に割れる、
 * (2) 助詞の向こう側で同じ数字が繰り返されると語の割りの重複落しが吞む
 * （`2026 年 8 月 と 2026 年 9 月` の二度目の `2026` が落ち、年の抜けた `9月` ＝
 * 全年分に化けて 412 行に対して 423 行出た）、(3) 年を添えた月の語（`2026年8月`）が
 * 列挙の一片として解けず、並べた形が 0 行に落ちる（`2026年8月と2026年9月` **0 行**）。
 * 実測値を張るのは検査用ビルドの品書（tests/built_site.ts – 435 行）– 実ビルドと
 * 行数は違うので、空格 ≡ 詰め形の対称差 0 と共に、其の方で測つた行数を張る
 * （第 455 回・第 456 回の流儀）。月を決まらない日の列挙（`5 日 と 6 日`）は
 * 解かない侭（第 395 回 – 締切の推測はしない）、語その物が助詞の打ち方
 * （『と』だけ・『ai と』・『きょうと』）は第 419 回の侭。 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { builtSite } from "./built_site.ts";

const 基準 = Date.parse("2026-08-09T00:00:00Z");

function 品書(): string[] {
  return (
    Recommender.candidateRows(
      JSON.parse(readFileSync(join(builtSite(), "catalog.json"), "utf8")) as unknown as never,
    ) as unknown as Array<{ hay: string }>
  ).map((行) => String(行.hay));
}

function 対称差(x: Set<string>, y: Set<string>): number {
  let n = 0;
  for (const a of x) if (!y.has(a)) n += 1;
  for (const b of y) if (!x.has(b)) n += 1;
  return n;
}

describe("空格で離した列挙が詰め形と同じ行に出る（第 457 回）", () => {
  const 品 = 品書();
  const 列 = (q: string): Set<string> => {
    const 当 = Recommender.searchMatcher(q, 基準);
    return new Set(品.filter((行) => 当(行) === true));
  };

  /* [空格で離した打ち方, 詰めた打ち方, 検査用ビルドの品書で測つた実行数]
   * – 実ビルドでは `8月と9月` 441 行・`12月と1月` 290 行・`8月10日と8月20日` 17 行・
   *   `8月10日と11日` 7 行・`8月と9月と10月` 588 行・`2026年8月と2026年9月` 412 行。 */
  const 組: Array<[string, string, number]> = [
    ["8 月と 9 月", "8月と9月", 284],
    ["8 月 と 9 月", "8月と9月", 284],
    ["1 月 と 2 月", "1月と2月", 46],
    ["12 月 と 1 月", "12月と1月", 107],
    ["8 月 10 日 と 8 月 20 日", "8月10日と8月20日", 9],
    ["8 月 10 日 と 11 日", "8月10日と11日", 4],
    ["8 月 と 9 月 と 10 月", "8月と9月と10月", 359],
    ["8 月 または 9 月", "8月または9月", 284],
    ["2026 年 8 月 と 2026 年 9 月", "2026年8月と2026年9月", 283],
    ["3 日 後 と 5 日 後", "3日後と5日後", 20],
    /* 第 394 回・第 406 回で解ける事になつた形が、空格でも壊れて居ない事。 */
    ["明日 と 明後日", "明日と明後日", 4],
    ["来週 と 再来週", "来週と再来週", 61],
    ["月曜 と 金曜", "月曜と金曜", 126],
    ["上旬 と 下旬", "上旬と下旬", 68],
  ];

  for (const [空格, 詰め, 期待] of 組) {
    it(`「${空格}」は「${詰め}」と同じ行が出て ${期待} 行`, () => {
      const 空 = 列(空格);
      const 詰 = 列(詰め);
      expect(対称差(空, 詰), `対称差が出た: ${空格} ⇔ ${詰め}`).toBe(0);
      /* 詰め形が実質の行を引いて居る事（空振りの対称差 0 を防ぐ – 第 455 回）。 */
      expect(詰.size, `詰め形が ${期待} 行で無い: ${詰め}`).toBe(期待);
      expect(空.size, `空格形が ${期待} 行で無い: ${空格}`).toBe(期待);
    });
  }

  /* 語組（当たり方と件数欄の案内の元）も詰め形と一字一句同じ – 行数だけでなく
   * 「こう探しました」の文も同じになる事をここで張る。 */
  for (const [空格, 詰め] of 組.slice(0, 8)) {
    it(`「${空格}」の語組は「${詰め}」と等しい`, () => {
      expect(JSON.stringify(Recommender.queryTokenGroups(空格, 基準))).toBe(
        JSON.stringify(Recommender.queryTokenGroups(詰め, 基準)),
      );
    });
  }

  /* 断つた物 – 測つて、寄せないと決めた形（締切の推測はしない）。 */
  it("月を決まらない日の列挙は寄せない（詰め形は 0 行の侭 – 第 395 回）", () => {
    /* 空格形は語の積として通る（詰め形 `5日と6日` は解けない語で一語のまま 0 行）。
     * 列挙として解かない決まりは動かさない – 月を推して行を広げない。 */
    expect(列("5 日 と 6 日").size).toBe(4);
    expect(列("5日と6日").size).toBe(0);
    expect(列("10 日 と 20 日").size).toBe(5);
    expect(列("10日と20日").size).toBe(0);
  });

  it("列挙の機械が解かない助詞（`や`）は和集合にならない（詰め形と同じ – 第 457 回）", () => {
    /* `や` は列挙の区切りの表に無い – 詰め形でも空格でも和集合にはならず、語の積に
     * なる（実測 – 詰め形 `8月や9月` 22 行 – 検査用ビルド 13 行）。空格側は第 458 回で
     * 挟まれた助詞を落とすので、其の方の詰め形と同じ行に出る。 */
    expect(対称差(列("8 月 や 9 月"), 列("8月や9月"))).toBe(0);
    expect(列("8月や9月").size).toBe(13);
  });

  it("語の末尾で立つ格助詞は今まで通り剥ぐ（第 419 回を壊さない）", () => {
    expect(列("ai と").size).toBe(164);
    expect(対称差(列("ai と"), 列("aiと"))).toBe(0);
    expect(列("ai").size).toBe(164);
    /* 語その物が助詞で了う打ち方は剥がない – 空の検索語にして全行を出さない。 */
    expect(列("と").size).toBeLessThan(80);
    /* 平仮名だけの語は守る（『きょうと』→『きょう』に化けない – 第 419 回）。 */
    expect(列("きょうと").size).toBe(2);
  });

  it("暦日の語では無い物の列挙は寄せない（締切の推測はしない）", () => {
    expect(列("人と機械").size).toBe(0);
    expect(列("8 月 と 機械").size).toBe(0);
    expect(列("第 2 ラウンド と 第 3 ラウンド").size).toBe(3);
    /* 詰め形の方が 0 行（列挙として解けない形の語が詰まると割れなくなる） –
     * 空格側は第 456 回より前の当たり方の侭なので、之は今度の種として張る。 */
    expect(列("第2ラウンドと第3ラウンド").size).toBe(0);
  });

  /* 第 456 回の形が壊れて居ない事（同じ数字の繰り返しを落とさない目）。 */
  it("第 456 回の空格暦日は其侭通る", () => {
    expect(対称差(列("8 月 22 日"), 列("8月22日"))).toBe(0);
    expect(対称差(列("12 月 31 日 まで"), 列("12月31日まで"))).toBe(0);
    expect(対称差(列("1 月 1 日"), 列("1月1日"))).toBe(0);
  });
});

