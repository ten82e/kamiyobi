import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { builtSite } from "./built_site.ts";

const 基準 = Date.parse("2026-08-09T00:00:00Z");

function 品書(): Array<{ hay: string }> {
  const 物 = JSON.parse(readFileSync(join(builtSite(), "catalog.json"), "utf8")) as unknown;
  return Recommender.candidateRows(物) as unknown as Array<{ hay: string }>;
}

const 全行 = 品書();

function 件数(文: string): number {
  const 照合 = Recommender.searchMatcher(文, 基準);
  return 全行.filter((行) => 照合(String(行.hay)) === true).length;
}

function 行列表(文: string): string[] {
  const 照合 = Recommender.searchMatcher(文, 基準);
  return 全行.filter((行) => 照合(String(行.hay)) === true).map((行) => String(行.hay));
}

/** 畫面が 0 件時に出す案内の文（六道を並べた一字列）。 */
function 案内(文: string): string {
  return [
    Recommender.columnQueryNoteJa(文),
    Recommender.uiWordNoteJa(文),
    Recommender.dayRangeNoteJa(文),
    Recommender.wholeTableQueryNoteJa(文),
    ...(Recommender.relativeDayNotes(文, 基準) || []),
    ...Recommender.querySynonymNotes(文),
  ]
    .filter(Boolean)
    .join(" ∥ ");
}

function 語列(文: string): string {
  return (Recommender.queryTokens(文, 基準) as string[]).join("|");
}

/** 群の一覧をビルド成果物から読む（第 512 回の棚卸し檢査と同じ讀み方）。 */
function 群の本文(): string {
  const 物 = readFileSync(join(builtSite(), "recommender.js"), "utf8");
  const 始 = 物.indexOf("const UI_WORD_GROUPS_JA = [");
  expect(始, "群の一覧が見つからない（組み立て方が変はつた）").toBeGreaterThan(0);
  const 後 = 物.slice(始);
  const 終 = 後.match(/\n\s*\];/);
  expect(終, "群の一覧の終りが見つからない").not.toBeNull();
  return 後.slice(0, 終 ? 終.index : 後.length);
}

/** 繋がれた打ち方を受ける群（斷り書きの文の頭が「という繋ぎ方では」の物）。 */
function 繋がれた打ち方の群(): { words: string[]; note: string; live: string } {
  const 塊々 = 群の本文()
    .split(/\n\s+\{\n/)
    .slice(1);
  const k = 塊々.findIndex((塊) => 塊.includes("という繋ぎ方では"));
  expect(k, "繋がれた打ち方を受ける群が見つからない").toBeGreaterThan(-1);
  const 塊 = 塊々[k];
  const 清 = 塊.replace(/\/\*[\s\S]*?\*\//g, "");
  const 合 = 塊.match(/words:\s*\[([\s\S]*?)\]/);
  const 取 = (名: string) => {
    const 目 = new RegExp(`\\n\\s*${名}:\\s*(?:\\n\\s*)?"((?:[^"\\\\]|\\\\.)*)"`);
    const m = 清.match(目);
    return m ? m[1] : "";
  };
  return {
    words: [...(合 ? 合[1].replace(/\/\*[\s\S]*?\*\//g, "") : "").matchAll(/"([^"]+)"/g)].map(
      (m) => m[1],
    ),
    note: 取("note"),
    live: 取("live"),
  };
}

