/**
 * 格助詞（を・と・へ）で閉じた打ち方（『来週を』『ai と』『午後を』）– 第 419 回。
 *
 * 実測（2026-10-08 – 2026-08-09 生成の実ビルドの品書 872 行・固定時刻 2026-08-09T00:00:00Z）:
 * 語を格助詞で閉じると**全部 0 行・案内も無し**だった – `来週` 53 行 / `来週を` **0 行**・
 * `明日` 4 行 / **0 行**・`年内` 772 行 / **0 行**・`8月22日` 12 行 / **0 行**・`中旬` 74 行 /
 * **0 行**・`三日以内` 17 行 / **0 行**・`来月上旬` 88 行 / **0 行**・`午後` 562 行 / `午後を`
 * **0 行**・`17時` 2 行 / **0 行**・`23:59` 507 行 / **0 行**、分野語も同じで `ml` 99 行 /
 * `mlを` **0 行**・`ai` 331 行 / `aiと` **0 行**・`セキュリティ` 152 行 / **0 行**・
 * `関西` 6 行 / **0 行**（`へ` も同じ – 『明日へ』0 行）。
 *
 * 原因 – 助詞の表（QUERY_PARTICLE_SPLIT_CHARS）に `を` `へ` は在るが、語の**末尾**に付くと
 * 割れて残る語が一つになるので、割れた語を採用する検査（二字以上が二つ以上）で捨てられて居た。
 * `と` は其の表にすら無い。は・が・も・で・に・かは日付の語の助詞の表が受けるので、格助詞だけが
 * 壁だった（敬語で閉じた打ち方 – 第 417 回 – と同じ形）。
 *
 * 直し – 検索語の折りで語尾の格助詞を剥がす。一文字で了う語を守る為、残りが一字になる剥ぎ方は
 * しない（『こと』→『こ』 – 実測で『と』その物は 121 行当たる – を受けない）。
 *
 * 下の検査は検査用ビルドの品書（435 行）で見る。
 */

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { builtSite } from "./built_site.ts";

const 基準 = Date.parse("2026-08-09T00:00:00Z");

function 列表入口() {
  const 品 = (
    Recommender.candidateRows(
      JSON.parse(readFileSync(join(builtSite(), "catalog.json"), "utf8")) as unknown as never,
    ) as unknown as Array<{ hay: string }>
  ).map((行) => String(行.hay));
  const 済 = new Map<string, Set<string>>();
  return (語: string): Set<string> => {
    if (!済.has(語)) {
      const 当 = Recommender.searchMatcher(語, 基準);
      済.set(語, new Set(品.filter((行) => 当(行) === true)));
    }
    return 済.get(語) as Set<string>;
  };
}

const 列 = 列表入口();

function 対称差(甲: string, 乙: string): number {
  const A = 列(甲);
  const B = 列(乙);
  return [...A].filter((行) => !B.has(行)).length + [...B].filter((行) => !A.has(行)).length;
}

/** 格助詞を付けた形が、付けない形と一寸もちがわない事を檢査する組。 */
const 組 = (語: string) =>
  [
    [`${語}を`, 語],
    [`${語}と`, 語],
    [`${語}へ`, 語],
  ] as const;

describe("格助詞で閉じた打ち方", () => {
  it("日付の語 + を・と・へ は其の方の語と同じ行を出す", () => {
    for (const 語 of ["来週", "明日", "今週", "来月", "8月22日"]) {
      for (const [打ち, 基] of 組(語)) {
        expect(列(基).size, `「${基}」の行が在らない（検査が空振り）`).toBeGreaterThan(0);
        expect(対称差(打ち, 基), `「${打ち}」が「${基}」と違う行を出した`).toBe(0);
      }
    }
  });

  it("幅の語・月の幅 + を（『年内を』『三日以内を』『来月上旬を』『中旬を』）", () => {
    for (const 語 of ["年内", "三日以内", "来月上旬", "中旬", "8月", "来週中", "来週末"]) {
      for (const [打ち, 基] of 組(語)) {
        expect(列(基).size, `「${基}」の行が在らない`).toBeGreaterThan(0);
        expect(対称差(打ち, 基), `「${打ち}」が「${基}」と違う行を出した`).toBe(0);
      }
    }
  });

  it("午前後の帯と時刻の語 + を（『午後を』『23:59を』『08:59と』）", () => {
    for (const 語 of ["午後", "午前", "23:59", "08:59"]) {
      for (const [打ち, 基] of 組(語)) {
        expect(列(基).size, `「${基}」の行が在らない`).toBeGreaterThan(0);
        expect(対称差(打ち, 基), `「${打ち}」が「${基}」と違う行を出した`).toBe(0);
      }
    }
  });

  it("分野の語・会場・状態の語 + を（『aiと』『セキュリティを』『関西を』）", () => {
    for (const 語 of ["ai", "ml", "セキュリティ", "関西", "未定", "機械学習"]) {
      for (const [打ち, 基] of 組(語)) {
        expect(列(基).size, `「${基}」の行が在らない`).toBeGreaterThan(0);
        expect(対称差(打ち, 基), `「${打ち}」が「${基}」と違う行を出した`).toBe(0);
      }
    }
  });

  it("敬語と重なっても打ち直せる（『mlとです』『来週を でした』）", () => {
    for (const [打ち, 基] of [
      ["mlとです", "ml"],
      ["来週を でした", "来週"],
      ["ai を", "ai"],
      ["セキュリティをですよ", "セキュリティ"],
    ] as const) {
      expect(列(基).size, `「${基}」の行が在らない`).toBeGreaterThan(0);
      expect(対称差(打ち, 基), `「${打ち}」が「${基}」と違う行を出した`).toBe(0);
    }
  });

  it("句読体で閉じた形も受ける（『来週を。』）", () => {
    for (const 打ち of ["来週を。", "ai と！", "午後を…"]) {
      const 基 = 打ち.replace(/[をとへ][、。，．,.!?！？〜~…\s]*$/, "");
      expect(列(基).size, `「${基}」の行が在らない`).toBeGreaterThan(0);
      expect(対称差(打ち, 基), `「${打ち}」が「${基}」と違う行を出した`).toBe(0);
    }
  });
});

describe("語その物を壊さない", () => {
  it("残りが一字になる剥ぎ方はしない（『こと』を『こ』に化かさない）", () => {
    /* 一字の語は行の文字列で大量に当たる – 寄せた側が基より広くなる（第 417 回と同じ決まり）。
     * 『あと』が『あ』に化けて居ない事を、兩方の行集合が違ふ事で見る（化けたら對稱差 0 になる）。 */
    expect(列("こと").size, "『こと』が『こ』に化けた").toBe(0);
    expect(列("ごと").size, "『ごと』が『ご』に化けた").toBe(0);
    expect(列("へ").size, "『へ』が空の検索語に化けた").toBe(0);
    expect(対称差("あと", "あ"), "『あと』が『あ』に化けた").toBeGreaterThan(0);
  });

  it("格助詞その物の打ち方は其侭（空の検索語にしない）", () => {
    /* 語その物が格助詞で了う形は剥がない – 空の検索語にすると全行に出る（実測: 『と』だけ 65 行・
     * 『を』だけ 1 行 / 檢査用ビルド 435 行）。 */
    expect(列("と").size, "『と』だけで全行に出た").toBeLessThan(80);
    expect(列("を").size, "『を』だけで全行に出た").toBeLessThan(80);
    expect(列("ml").size, "『ml』が壊れた").toBeGreaterThan(0);
  });

  it("其の他の助詞・敬語の当たり方も其侭", () => {
    expect(列("です").size, "『です』だけで行が出るようになった").toBe(0);
    expect(列("来週です").size, "敬語の折りが壞れた").toBe(列("来週").size);
    expect(列("すね").size, "『すね』が『す』に化けた").toBe(0);
    expect(列("明日な").size, "『明日な』まで受けてしまった").toBe(0);
    expect(対称差("しまね", "島根"), "『しまね』が『島根』と違う行を出した").toBe(0);
    /* ひらがなの地名は格助詞と同じ字を末尾に持つ（『きょうと』の『と』 – 実測で京都の行が
     * 2 行出る語を『きょう』に化かさない – 割れた語を採用する検査が守つて居た物と同じ穴）。*/
    expect(列("きょうと").size, "『きょうと』の行が在らない（検査が空振り）").toBeGreaterThan(0);
    expect(対称差("きょうと", "京都"), "『きょうと』が『京都』と違う行を出した").toBe(0);
    expect(対称差("こと", "こ"), "『こと』が『こ』に化けた").toBeGreaterThan(0);
  });

  it("成果物に格助詞の語尾の表が一つ在り、敬語の後に試す順番で在る", () => {
    const 物 = readFileSync(join(builtSite(), "recommender.js"), "utf8");
    for (const [形, 度] of [
      ["const 格助詞の語尾Ja =", 1],
      ["const 平仮名だけJa =", 1],
      ['格を剥いだ = 文.replace(格助詞の語尾Ja, "")', 1],
    ] as const) {
      const 数 = 物.split(形).length - 1;
      expect(数, `「${形}」が ${数} 回（期待 ${度} 回）`).toBe(度);
    }
    /* 敬語を先に試し、其処で剥げなかった時だけ格助詞を試す順番（両方試すと『mlとです』の
     * 『とです』が途中で切れて化ける – 敬語の表を先に置く決まりの続き）。其の間に平仮名の
     * 守りが在る事も見る（無いと『きょうと』が『きょう』に化ける）。 */
    const 敬語の試す所 = 物.indexOf('文.replace(敬語の語尾Ja, "")');
    const 格助詞の試す所 = 物.indexOf('文.replace(格助詞の語尾Ja, "")');
    expect(敬語の試す所, "敬語を剥ぐ箇所が見つからない").toBeGreaterThan(-1);
    expect(格助詞の試す所, "格助詞を剥ぐ箇所が見つからない").toBeGreaterThan(敬語の試す所);
    const 間 = 物.slice(敬語の試す所, 格助詞の試す所 + 900);
    expect(間, "敬語で剥げなかった時だけ格助詞を試す決まりが消えた").toMatch(
      /if\s*\(\s*次 === 文\s*\)/,
    );
    expect(間, "平仮名だけの語を守る決まりが消えた").toMatch(/平仮名だけJa\.test\(文\)/);
  });
});
