/**
 * 冠の無い日（`8月10日から12日` の `12日`）を端に置く幅の検査。SPEC §4・§7・第 376 回。
 * 実測（2026-10-24 – 実ビルドの品書 872 行・固定時刻 2026-08-09T00:00:00Z）の直し前は、
 * 其の方の月を付けた形だけが通っていた –
 *   `8月10日から8月12日` 10 行 / `8月10日から12日` **0 行**・`8月10日から20日` **0 行**・
 *   `8月25日から28日` **0 行**・`12月28日から3日` **0 行**・`令和8年8月10日から12日` **0 行**。
 * 原因（第 371 回で「直っても 0 語」だった理由 – 第 376 回で究明）: 暦日の幅の規則が尾側を
 * `12日` の形でも受ける為、其の枝が其の方の語の入口まで届かず、其の日を解けずに黙っていた。
 */

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { builtSite } from "./built_site.ts";

const 基準 = Date.parse("2026-08-09T00:00:00Z");

function 目録(): ReturnType<typeof Recommender.candidateRows> {
  return Recommender.candidateRows(
    JSON.parse(readFileSync(join(builtSite(), "catalog.json"), "utf8")),
  );
}

function 行列表(語: string): string[] {
  const マッチ = Recommender.searchMatcher(語, 基準);
  return 目録()
    .filter((行) => マッチ(行.hay) === true)
    .map((行) => 行.hay);
}

function 対称差(a: string, b: string): number {
  const x = new Set(行列表(a));
  const y = new Set(行列表(b));
  return [...x].filter((k) => !y.has(k)).length + [...y].filter((k) => !x.has(k)).length;
}

function 幅の案内(語: string): string {
  const 組 = Recommender.dayRangePairs(語, 基準) as unknown as Array<[string, string]>;
  return 組.map(([, 範囲]) => 範囲).join(" ") || "（なし）";
}

describe("冠の無い日を端に置く幅", () => {
  it("其の方の月を付けた形と同じ行を出す（其の日を継ぐ）", () => {
    for (const [語, 暦] of [
      ["8月10日から12日", "8月10日から8月12日"],
      ["8月10日から20日", "8月10日から8月20日"],
      ["8月25日から28日", "8月25日から8月28日"],
      /* 其の日が頭側より小さい日は翌月に回る（12 月 28 日から 3 日は年をまたぐ）。 */
      ["12月28日から3日", "2026年12月28日から2027年1月3日"],
      /* 和暦で打たれた片側も其の方の暦日に解ける。 */
      ["令和8年8月10日から12日", "8月10日から8月12日"],
    ] as Array<[string, string]>) {
      expect(対称差(語, 暦), `『${語}』が『${暦}』と違う行を出している`).toBe(0);
      expect(行列表(語).length, `『${語}』が行を出さない`).toBeGreaterThan(0);
    }
  });

  it("区切りの記号・『まで』を付けた形も同じ行を出す", () => {
    for (const 形 of [
      ["8月10日から12日", "8月10日〜12日", "8月10日から12日まで"],
      ["8月25日から28日", "8月25日〜28日"],
      ["令和8年8月10日から12日", "令和8年8月10日〜12日"],
    ] as Array<string[]>) {
      const 頭 = 形[0];
      for (const 語 of 形.slice(1)) {
        expect(対称差(頭, 語), `『${語}』が『${頭}』と違う行を出している`).toBe(0);
      }
    }
  });

  it("其の方の日だけで通る行を必ず含む（幅は其の方の日より狭くならない）", () => {
    const 幅 = new Set(行列表("8月10日から12日"));
    for (const 片側 of ["8月10日", "8月11日", "8月12日"]) {
      for (const 行 of 行列表(片側)) {
        expect(幅.has(行), `『8月10日から12日』が『${片側}』の行を落とした`).toBe(true);
      }
    }
    expect(
      行列表("8月10日から12日").length,
      "『8月10日から12日』が『8月10日から8月12日』より狭い",
    ).toBeGreaterThanOrEqual(行列表("8月10日から8月12日").length);
  });

  it("件数欄に打たれた語と解決した暦日の範囲を書く（固定時刻 2026-08-09T00:00:00Z）", () => {
    expect(幅の案内("8月10日から12日"), "其の日を継いだ幅の範囲が違う").toBe(
      "2026年8月10日から2026年8月12日",
    );
    expect(幅の案内("8月10日から20日"), "暦日の幅（第 371 回で置いていた形）の範囲が違う").toBe(
      "2026年8月10日から2026年8月20日",
    );
    expect(幅の案内("12月28日から3日"), "年をまたぐ幅の範囲が違う").toBe(
      "2026年12月28日から2027年1月3日",
    );
    expect(幅の案内("令和8年8月10日から12日"), "和暦の片側を継いだ幅の範囲が違う").toBe(
      "2026年8月10日から2026年8月12日",
    );
  });

  it("解けない形は黙る（月の決まらない幅・在らない日 – 締切の推測はしない）", () => {
    for (const 語 of [
      "12日から15日" /* 何月の話か決まらない */,
      "8月10日から32日" /* 32 日という日は在らない */,
      "2月28日から30日" /* 其の月は 30 日が在らない – 無い日に繰り上げない */,
      "今週金曜から日曜" /* どの週の日曜か決まらない（第 373 回と同じ扱い） */,
    ]) {
      expect(幅の案内(語), `『${語}』を無理に解いた`).toBe("（なし）");
      expect(行列表(語).length, `『${語}』が行を出した`).toBe(0);
    }
  });

  it("其れ以外の幅の形（其の方の語・其の方の規則）は其侭通る", () => {
    expect(対称差("8月10日から8月20日", "8/10〜8/20")).toBe(0);
    expect(対称差("12月25日から1月10日", "12月25日〜1月10日")).toBe(0);
    expect(対称差("来月から再来月", "来月〜再来月")).toBe(0);
    expect(対称差("明日から明後日", "明日〜明後日")).toBe(0);
    expect(対称差("来月上旬から中旬", "2026年9月1日から2026年9月20日")).toBe(0);
    expect(行列表("12日").length, "冠の無い日其れ自体が通らなくなった").toBeGreaterThan(0);
  });
});

describe("成果物", () => {
  it("直し方が実測どおりの形で成果物に入っている", () => {
    const rec = readFileSync(join(builtSite(), "recommender.js"), "utf8");
    const 条目列表: Array<[string, number]> = [
      ["const 前 = 幅の片側を暦日に解くJa(前語", 1],
      ['"尾", hint)', 1],
      ["const 裸の日 =", 1],
      ["月のhint.length === 4 && 月のhint[3] === 1", 1],
      /* 頭側が月を打っている時のみ冠の無い日を其の日として受ける（`今日から3日` は日数）。 */
      ["/[0-9]{1,2}月|[0-9]{1,2}[-/][0-9]{1,2}/.test(前語)", 1],
      ["const 和暦 = eraYearTermsJa(語);", 1],
      /* 語を結ぶ規則の語の列挙に冠の無い日が在る（`8月10日〜12日` が 〜 で割れない為）。 */
      ["|[0-9]{1,2}日)", 1],
    ];
    for (const [条目, 数] of 条目列表) {
      expect(rec.split(条目).length - 1, `成果物の中の語の数: ${条目.slice(0, 18)}`).toBe(数);
    }
  });
});
