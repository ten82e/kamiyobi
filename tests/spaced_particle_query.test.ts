/* 第 458 回 – 助詞を空格で離って打つ人が、詰めて打つ人と同じ行に届くようにした
 * （`論文 の 締切` `8 月 の 締切` `8 月 は 締切` `来週 の` `2026 年 8 月 の` 等）。
 * 実測（2026-11-05 – 実ビルドの品書 872 行・固定時刻 2026-08-09T00:00:00Z）:
 * 詰め形は通る（`論文の締切` 461 行・`8月の締切` 189 行・`8月は締切` 189 行・
 * `国内の会議` 38 行・`mlの会議` 99 行・`来週の締切` 50 行・`8月22日の締切` 11 行・
 * `8月の` 210 行・`来週の` 53 行・`2026年8月の` 189 行・`今週の` 19 行）のに、
 * 助詞を離しただけで `論文 の 締切` 206 行・`8 月 の 締切` 42 行・`8 月 は 締切`
 * 4 行・`国内 の 会議` 5 行・`ml の 会議` 49 行・`来週 の 締切` 3 行・
 * `8 月 22 日 の 締切` 1 行・`8 月 の` 48 行・`来週 の` 4 行・`2026 年 8 月 の`
 * 34 行に化けて居た。詰め形では助詞は語の区切りとして消える（第 341 回）ので、
 * 助詞だけの語が立った時にだけ其れを落とし、其れ以外（『の』だけ 390 行・
 * 『論文の』0 行）は壊さない。月を書いていない日の列挙（第 395 回）と語その物が
 * 助詞の打ち方（第 417 回・第 419 回・第 457 回）は其侭。実測値を張るのは検査用
 * ビルドの品書（tests/built_site.ts – 435 行）– 実ビルド（872 行）とは行数が違う
 * ので、空格 ≡ 詰め形の対称差 0 と共に其の方で測つた行数を張る（第 455 回 –
 * 第 457 回の流儀）。 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { builtSite } from "./built_site.ts";

const 基準 = Date.parse("2026-08-09T00:00:00Z");

function 品書(): string[] {
  return (
    Recommender.candidateRows(
      JSON.parse(readFileSync(join(builtSite(), "catalog.json"), "utf8")) as unknown as never,
    ) as unknown as Array<{ hay: string }>
  ).map((行) => String(行.hay));
}

function 対称差(x: Set<string>, y: Set<string>): number {
  let n = 0;
  for (const a of x) if (!y.has(a)) n += 1;
  for (const b of y) if (!x.has(b)) n += 1;
  return n;
}

describe("空格で離した助詞が詰め形と同じ行に出る（第 458 回）", () => {
  const 品 = 品書();
  const 列 = (q: string): Set<string> => {
    const 当 = Recommender.searchMatcher(q, 基準);
    return new Set(品.filter((行) => 当(行) === true));
  };

  /* 二つの語に挟まれた助詞 – [空格, 詰め, 検査用ビルドで測つた実行数]
   * – 実ビルドでは `論文の締切` 461 行・`8月の締切` 189 行・`国内の会議` 38 行・
   *   `mlの会議` 99 行・`来週の締切` 50 行・`8月22日の締切` 11 行。 */
  const 挟まる: Array<[string, string, number]> = [
    ["論文 の 締切", "論文の締切", 264],
    ["8 月 の 締切", "8月の締切", 114],
    ["8 月 は 締切", "8月は締切", 114],
    ["8 月 で 締切", "8月で締切", 114],
    ["8 月 に 締切", "8月に締切", 114],
    ["国内 の 会議", "国内の会議", 38],
    ["ml の 会議", "mlの会議", 18],
    ["来週 の 締切", "来週の締切", 43],
    ["来月 の 締切", "来月の締切", 153],
    ["8 月 22 日 の 締切", "8月22日の締切", 4],
    ["セキュリティ の 会議", "セキュリティの会議", 68],
    ["AI の 学会", "AIの学会", 2],
    ["来週 の 月曜", "来週の月曜", 2],
    ["今週 の 金曜", "今週の金曜", 1],
    /* `や` は列挙の区切りの表に無いので和集合にはなら無いが、詰め形とは同じになる。 */
    ["8 月 や 9 月", "8月や9月", 13],
  ];

  for (const [空格, 詰め, 期待] of 挟まる) {
    it(`「${空格}」は「${詰め}」と同じ行が出て ${期待} 行`, () => {
      const 空 = 列(空格);
      const 詰 = 列(詰め);
      expect(対称差(空, 詰), `対称差が出た: ${空格} ⇔ ${詰め}`).toBe(0);
      /* 詰め形が実質の行を引いて居る事（空振りの対称差 0 を防ぐ – 第 455 回）。 */
      expect(詰.size, `詰め形が ${期待} 行で無い: ${詰め}`).toBe(期待);
      expect(空.size, `空格形が ${期待} 行で無い: ${空格}`).toBe(期待);
    });
  }

  /* 語の末尾で立つ助詞 – 前語が其の日として解ける時だけ寄せる（詰め形の日付の語の
   * 語尾の表が `8月の` `来週の` を受けるのと同じ行）。 */
  const 末尾: Array<[string, string, number]> = [
    ["8 月 の", "8月の", 118],
    ["2026 年 8 月 の", "2026年8月の", 118],
    ["来週 の", "来週の", 43],
    ["今週 の", "今週の", 4],
    ["来月 の", "来月の", 178],
    ["8 月 22 日 の", "8月22日の", 4],
    ["月曜 の", "月曜の", 59],
    /* 12 月 31 日は検査用ビルドの品書に 0 行（実ビルドでは 2 行）なので、
     * 検査用ビルドで行の在る `上旬` を張る。 */
    ["上旬 の", "上旬の", 10],
  ];

  for (const [空格, 詰め, 期待] of 末尾) {
    it(`語の末尾の助詞「${空格}」は「${詰め}」と同じ行が出て ${期待} 行`, () => {
      const 空 = 列(空格);
      const 詰 = 列(詰め);
      expect(対称差(空, 詰), `対称差が出た: ${空格} ⇔ ${詰め}`).toBe(0);
      expect(詰.size, `詰め形が ${期待} 行で無い: ${詰め}`).toBe(期待);
      expect(空.size, `空格形が ${期待} 行で無い: ${空格}`).toBe(期待);
    });
  }

  /* 語組（当たり方と件数欄の案内の元）も詰め形と一字一句同じ。 */
  /* 語の末尾で立つ `の` は其の語を捨てるので、語組に出る語の形は打ち方に従う
   * （`来週 の` は「来週」・`来週の` は「来週の」 – 行は同じ）。 */
  for (const [空格, 詰め] of 挟まる.slice(0, 8)) {
    it(`「${空格}」の語組は「${詰め}」と等しい`, () => {
      expect(JSON.stringify(Recommender.queryTokenGroups(空格, 基準))).toBe(
        JSON.stringify(Recommender.queryTokenGroups(詰め, 基準)),
      );
    });
  }

  /* 断つた物 – 測つて、落とさないと決めた形。 */
  it("語その物が助詞の打ち方は其侭（空の検索語にしない – 第 417 回・第 419 回）", () => {
    /* 一語だけで了う打ち方は落ちない（落すと空の検索語 = 全行になる）。 */
    expect(列("の").size).toBe(175);
    expect(列("を").size).toBe(1);
    expect(列("は").size).toBe(4);
    expect(列("が").size).toBe(13);
    expect(列("も").size).toBe(11);
    expect(列("で").size).toBe(78);
    /* 語の頭で立つ助詞も落さない（前后の語が要る – 実測 `の 締切` 151 行は
     * 打ち直し前から同じ – 詰め形 `の締切` は 0 行なので寄せない）。 */
    expect(列("の 締切").size).toBe(151);
    expect(列("の締切").size).toBe(0);
  });

  it("詰め形の方が壊れて居た形も第 459 回で同じ行に出る（語尾の助詞を剥ぐやうにした為）", () => {
    /* 第 458 回当時は詰め形 `論文の` が 0 行なので、空格形を其の方に寄せなかった –
     * 寄せると 109 行 → 0 行の後退になつた（測つた）。第 459 回で詰め形側の語尾の助詞も
     * 剥ぐやうにしたので、打ち方の違いで行が変はらなくなつた。 */
    expect(対称差(列("論文 の"), 列("論文の"))).toBe(0);
    expect(列("論文の").size).toBe(264);
    expect(対称差(列("国内 の"), 列("国内の"))).toBe(0);
    expect(列("国内の").size).toBe(38);
    expect(対称差(列("ml で"), 列("mlで"))).toBe(0);
    expect(列("mlで").size).toBe(18);
    /* 助詞が語の**頭**に貼り付いた形（`ml で締切` の『で締切』）は第 461 回で切れるやうに
     * なつた – 其の時は 0 行だつた（詰め形 `mlで締切` 14 行に並んだ）。 */
    expect(対称差(列("ml で締切"), 列("mlで締切"))).toBe(0);
    expect(列("mlで締切").size).toBe(14);
  });

  it("在ら無い日の語尾の助詞は寄せない（締切の推測はしない – 第 456 回）", () => {
    expect(列("4 月 31 日").size).toBe(0);
    expect(列("4 月 31 日 の").size).toBe(0);
    expect(列("2 月 30 日 の").size).toBe(0);
  });

  it("列挙の助詞は第 457 回の侭和集合に解ける", () => {
    expect(対称差(列("8 月 と 9 月"), 列("8月と9月"))).toBe(0);
    expect(列("8月と9月").size).toBe(284);
    expect(対称差(列("8 月 または 9 月"), 列("8月または9月"))).toBe(0);
  });

  it("第 456 回の空格暦日・第 457 回の空格列挙は其侭通る", () => {
    expect(対称差(列("12 月 31 日 まで"), 列("12月31日まで"))).toBe(0);
    expect(対称差(列("12 月 24 日 の までに"), 列("12月24日までに"))).toBe(0);
    expect(対称差(列("2026 年 8 月 と 2026 年 9 月"), 列("2026年8月と2026年9月"))).toBe(0);
    expect(列("12月31日まで").size).toBe(422);
  });
});

describe("直した形がビルド成果物に残る（第 458 回）", () => {
  const 物 = readFileSync(join(builtSite(), "recommender.js"), "utf8");

  it("二つの語に挟まれた助詞の語を落とす目が 1 箇所", () => {
    expect(
      物.split("const 残った語々 = 敬語を剥いだ語々.filter((語, 番) => 語.length > 0 &&").length -
        1,
    ).toBe(1);
    expect(物.split("!(語.length <= 2 &&").length - 1).toBe(1);
    expect(
      物.split("Array.from(語).every((字) => QUERY_PARTICLE_SPLIT_CHARS.indexOf(字) >= 0)").length -
        1,
    ).toBe(1);
  });

  it("語の末尾で立つ `の` を暦日の語から落とす目が 1 箇所", () => {
    expect(物.split('if (prev && token === "の" && 解ける日語かJa(prev))').length - 1).toBe(1);
  });

  it("助詞の表を書き写して居ない（語の表は正本の一か所だけ）", () => {
    expect(物.split("const QUERY_PARTICLE_SPLIT_CHARS = ").length - 1).toBe(1);
  });
});
