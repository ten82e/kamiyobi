/**
 * 相対語を二つ並べて打つ幅の検査。SPEC §4・§7・第 373 回。
 * 実測（2026-10-24 – 実ビルドの品書 872 行・固定時刻 2026-08-09T00:00:00Z）の直し前は、
 * 幅の両端が相対語の形が全部 0 行だった –
 *   `明日から明後日` **0 行**（`明日` 4 行・`明後日` 12 行）・`今週から来週` **0 行**
 *   （`今週` 19 行・`来週` 53 行）・`今週から再来週` **0 行**・`明日から8月20日` **0 行**・
 *   `3日後から5日後` **0 行**・`来週金曜から再来週金曜` **0 行**。
 * 其の方の語を並べただけの形（`今週〜来週` 1 行・`明日〜明後日` 3 行）は幅ではなく
 * **其の方の語を両方含む行**だった – 月の幅（第 370 回）と暦日の幅（第 371 回）は
 * 通るので、「幅の打ち方は通る」と思った人が黙って 0 行に当たっていた。
 */

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { builtSite } from "./built_site.ts";

const 基準 = Date.parse("2026-08-09T00:00:00Z");

function 目録(): ReturnType<typeof Recommender.candidateRows> {
  return Recommender.candidateRows(
    JSON.parse(readFileSync(join(builtSite(), "catalog.json"), "utf8")),
  );
}

function 行列表(語: string): string[] {
  const マッチ = Recommender.searchMatcher(語, 基準);
  return 目録()
    .filter((行) => マッチ(行.hay) === true)
    .map((行) => 行.hay);
}

function 対称差(a: string, b: string): number {
  const x = new Set(行列表(a));
  const y = new Set(行列表(b));
  return [...x].filter((k) => !y.has(k)).length + [...y].filter((k) => !x.has(k)).length;
}

function 幅の案内(語: string): string {
  const 組 = Recommender.dayRangePairs(語, 基準) as unknown as Array<[string, string]>;
  return 組.map(([, 範囲]) => 範囲).join(" ") || "（なし）";
}

describe("相対語を二つ並べて打つ幅", () => {
  it("区切りの記号が違っても同じ行を出す（其の方の語は其の方の幅）", () => {
    for (const 形 of [
      ["明日から明後日", "明日〜明後日", "明日-明後日", "明日から明後日まで"],
      ["今週から来週", "今週〜来週", "今週-来週", "今週から来週までに"],
      ["来週金曜から再来週金曜", "来週金曜〜再来週金曜", "来週金曜-再来週金曜"],
      ["明日から8月20日", "明日〜8月20日"],
      ["3日後から5日後", "3日後〜5日後"],
      ["今週末から来週末", "今週末〜来週末"],
      ["3日前から今日", "3日前〜今日"],
      ["先週から今週", "先週〜今週", "先週から今週まで"],
    ] as Array<string[]>) {
      const 頭 = 形[0];
      for (const 語 of 形.slice(1)) {
        expect(対称差(頭, 語), `『${語}』が『${頭}』と違う行を出している`).toBe(0);
      }
    }
  });

  it("其の方の語だけで通る行を必ず含む（幅は其の方の語より狭くならない）", () => {
    for (const [幅, 片側] of [
      ["明日から明後日", "明日"],
      ["明日から明後日", "明後日"],
      ["今週から来週", "今週"],
      ["今週から来週", "来週"],
      ["来週から再来週", "来週"],
    ] as Array<[string, string]>) {
      const 幅の行 = new Set(行列表(幅));
      for (const 行 of 行列表(片側)) {
        expect(幅の行.has(行), `『${幅}』が『${片側}』の行を落とした`).toBe(true);
      }
    }
    /* 其の方の語を並べただけの形（幅ではなく両方の語を含む行）より広い – 実測の嘘を止める所。 */
    expect(
      行列表("今週から来週").length,
      "『今週から来週』が『今週 来週』と同じ幅の無い形の侭",
    ).toBeGreaterThan(行列表("今週 来週").length);
    expect(
      行列表("明日から明後日").length,
      "『明日から明後日』が『明日 明後日』と同じ幅の無い形の侭",
    ).toBeGreaterThan(行列表("明日 明後日").length);
  });

  it("件数欄に打たれた語と解決した暦日の範囲を書く（固定時刻 2026-08-09T00:00:00Z）", () => {
    expect(幅の案内("明日から明後日"), "『明日から明後日』の範囲が違う").toBe(
      "2026年8月10日から2026年8月11日",
    );
    /* 週は月〜日の塊なので、頭は其の週の月曜、尾は其の週の日曜（上の暦の決まり）。 */
    expect(幅の案内("今週から来週"), "『今週から来週』の範囲が違う").toBe(
      "2026年8月3日から2026年8月16日",
    );
    expect(幅の案内("来週金曜から再来週金曜"), "週+曜日の幅の範囲が違う").toBe(
      "2026年8月14日から2026年8月21日",
    );
    expect(幅の案内("明日から8月20日"), "相対語と暦日を混ぜた幅の範囲が違う").toBe(
      "2026年8月10日から2026年8月20日",
    );
    expect(幅の案内("3日後から5日後"), "数の語を二つ並べた幅の範囲が違う").toBe(
      "2026年8月12日から2026年8月14日",
    );
    /* 月の変わり目を超える幅も其の方の暦の日数で歩く（月の長さを推測しない）。 */
    expect(幅の案内("3日前から今日"), "前側の数の語を含む幅の範囲が違う").toBe(
      "2026年8月6日から2026年8月9日",
    );
    expect(幅の案内("先週から今週"), "月を超える幅の範囲が違う").toBe(
      "2026年7月27日から2026年8月9日",
    );
    /* 其の方の語が其の方の規則に決まっている形は、此方が案内を出さない（月の幅 – 第 370 回、
       上旬・中旬・下旬 – 又の回、裸の曜日のみ – どの週か決まらない）。 */
    for (const 語 of ["来月から再来月", "金曜から月曜", "再来週中から来週中"]) {
      expect(幅の案内(語), `『${語}』を此方が受けてしまった`).toBe("（なし）");
    }
    /* 上旬・中旬・下旬を端に持つ幅は第 374 回で通るようになった（其れ前は「又の回」だった）。 */
    expect(
      対称差("8月中旬〜9月上旬", "2026年8月11日から2026年9月10日"),
      "旬を端に持つ幅が解けない",
    ).toBe(0);
    /* 逆向きの幅（`2日前から3日前`）は解かない – 来年として受けるのは打ち間違いを勝手に
       直し事になるので黙った侭にする（締切の推測はしない）。 */
    expect(幅の案内("2日前から3日前"), "逆向きの幅を解いてしまった").toBe("（なし）");
    expect(行列表("2日前から3日前").length, "逆向きの幅が行を出した").toBe(0);
  });

  it("其の方の語を其の方の幅として受ける形（暦日・月）は変わっていない", () => {
    expect(対称差("8月10日から8月20日", "8/10〜8/20")).toBe(0);
    expect(対称差("来月から再来月", "来月〜再来月")).toBe(0);
    expect(対称差("8月から11月", "8月〜11月")).toBe(0);
    /* 年の繰り越し – 打たれた月に年が無い幅は、終わりが基準より前なら翌年（締切の推測はしない）。 */
    expect(対称差("12月25日から1月10日", "12月25日〜1月10日")).toBe(0);
    expect(行列表("来月から再来月").length).toBeGreaterThan(0);
  });
});

describe("其れ以外の語の形が生きている事", () => {
  it("相対語の単体・『まで』・数の語の形は其の方の規則のまま", () => {
    for (const 語 of [
      "明日",
      "来週",
      "今週中",
      "来週金曜",
      "今週末",
      "3日後",
      "明日まで",
      "来月",
    ]) {
      expect(行列表(語).length, `『${語}』が通らなくなった`).toBeGreaterThan(0);
    }
    expect(対称差("明日まで", "明日までに")).toBe(0);
    /* 幅の語が其の方の語で立っていない形（`明日明後日`）は割らない – 黙った侭にする。 */
    expect(幅の案内("明日明後日")).toBe("（なし）");
  });
});

describe("成果物", () => {
  it("直し方が実測どおりの形で成果物に入っている", () => {
    const rec = readFileSync(join(builtSite(), "recommender.js"), "utf8");
    for (const [条目, 数] of [
      ["function 幅の片側を暦日に解くJa(", 1],
      ["function 暦日の語から解くJa(", 1],
      ["const 幅の区切りJa =", 1],
      ["const 相対日の語Ja =", 1],
      ['"から"));', 1],
      /* 両側は同じ入口で解く – 暦日の規則が受けた形も此処を通る（第 376 回）。 */
      ["幅の片側を暦日に解くJa(前語", 1],
      ['幅の片側を暦日に解くJa(後語, nowMs, "尾", hint)', 1],
    ] as Array<[string, number]>) {
      expect(rec.split(条目).length - 1, `成果物の中の語の数: ${条目.slice(0, 18)}`).toBe(数);
    }
  });
});
