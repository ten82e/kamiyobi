/**
 * 限定の助詞を繋げた打ち方（`機械学習だけ` `査読のみ` `9月だけ`）– 第 657 回。
 *
 * 實測（2026-08-09T00:00:00Z 生成の実ビルド・品書 3,250 行）で、「語 + だけ/のみ/しか」は
 * 內容語でも暦日の語でも**悉く 0 行で讓りも立たなかつた** – `機械学習` 504 行なのに
 * `機械学習だけ` 0 行・`査読` 32 行 / `査読のみ` 0 行・`関西` 26 / `関西だけ` 0・
 * `学生` 4 / `学生のみ` 0・`締切` 2,886 / `締切だけ` 0・`9月` 683 / `9月だけ` 0。
 * 一方、日付の側の DATE_TOKEN_TAILS_JA は既に「だけ」の一部を受けて居て（`来週だけ` 90 行・
 * `年内だけ` 1,042 行）、**同じ聞き方なのに片方だけ默る**不揃ひだつた。
 *
 * 限定の助詞は表を何も絞らない（其の語の行を出すだけ）なので、搜の側は落として同じ行に
 * 出會はせる。讓るのは – ①參加形式の語（『オンラインのみ』を `オンライン` 全体に廣げると
 * 噓になる – 其の方の寄せが先に動く）②平仮名だけの語（第 419 回の『しまね』）
 * ③剥いだ先が一字になる形。幅の語尾（`まで` `中`）は逆で讓すまゝ（第 398 回 – 剥ぐと期日が消える）。
 */
import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { REPO_ROOT } from "./helpers.ts";
import { queryReferenceSnapshotPath } from "./query_reference.ts";

const AT = Date.parse("2026-08-09T00:00:00Z");
const 品書檔案 = queryReferenceSnapshotPath();

type Row = { hay: string };
let 品書: Row[] | null = null;
/** 品書を记忆力せて讀む – ループ每に JSON を解析すると一檢で數分かかる（第 656 回の実測 484 秒）。*/
function 收錄(): Row[] {
  if (品書 === null) {
    const data = JSON.parse(readFileSync(品書檔案, "utf8"));
    品書 = Recommender.candidateRows(data) as Row[];
  }
  return 品書;
}

function 当たり(訪ね: string): number {
  const 寄 = Recommender.expandRelativeMonths(訪ね, AT);
  const 目 = Recommender.searchMatcher(寄, AT);
  return 收錄().filter((行) => 目(String(行.hay)) === true).length;
}

describe("限定の助詞を繋げた打ち方", () => {
  it("內容語 – 『語 + だけ/のみ/しか』は其の語と同じ行に出會ふ", () => {
    for (const 語 of ["機械学習", "査読", "関西", "学生", "締切", "ポスター", "ICS", "研究会"]) {
      expect(当たり(語), `前提 – 其の方の語で行が出る: ${語}`).toBeGreaterThan(0);
      for (const 助詞 of ["だけ", "のみ", "しか"]) {
        const 形 = `${語}${助詞}`;
        expect(当たり(形), `『${形}』が默つた（${語} は ${当たり(語)} 行）`).toBe(当たり(語));
      }
    }
  });

  it("暦日の語にも同じ助詞を通す（不揃ひを直した – 第 408 回から增し直した所）", () => {
    for (const 語 of ["9月", "12月", "来年", "8月10日", "明日", "3日後"]) {
      expect(当たり(語), `前提 – 其の方の日で行が出る: ${語}`).toBeGreaterThan(0);
      expect(当たり(`${語}だけ`), `『${語}だけ』が默つた`).toBe(当たり(語));
    }
    /* 幅の語尾は讓すまゝ – 剥ぐと解ける日が變はり期日が消える（第 398 回）。 */
    expect(当たり("12月31日まで"), "『まで』を剥いで幅を潰した").toBeGreaterThan(
      当たり("12月31日"),
    );
    expect(当たり("来週までに"), "『までに』を剥いだ").toBeGreaterThan(0);
    expect(当たり("8月20日から9月1日まで"), "幅の二日の打ち方を潰した").toBeGreaterThan(0);
  });

  it("讓る所 – 參加形式の語・平仮名だけの語・一字になる剥ぎ方", () => {
    /* 參加形式 – 『オンラインのみ』は印の行に寄せるので、搜の側が剥いてはいけない（第 503 回）。 */
    for (const 語 of ["オンライン", "ハイブリッド", "バーチャル", "対面"]) {
      for (const 助詞 of ["のみ", "だけ", "しか"]) {
        expect(
          当たり(`${語}${助詞}`),
          `『${語}${助詞}』が『${語}』と同じ広さに化けた`,
        ).toBeLessThanOrEqual(当たり(語));
      }
    }
    expect(当たり("オンラインのみ"), "參加形式の寄せが効かなくなった").toBeLessThan(
      当たり("オンライン"),
    );
    /* 平仮名だけの語 – 語その物を壞さん（第 419 回の『しまね』と同じ穴）。 */
    for (const 語 of ["しまね", "きょうと", "それ", "これ"]) {
      expect(当たり(`${語}のみ`), `平仮名だけの語『${語}』を割つた`).toBe(0);
      expect(当たり(`${語}だけ`), `平仮名だけの語『${語}』を割つた`).toBe(0);
    }
    /* 剥いだ先が一字になる形は讓す（二字以上 – 第 419 回と同じ門）。 */
    expect(当たり("年だけ"), "一字に縮める剥ぎ方をした").toBe(0);
    expect(当たり("会だけ"), "一字に縮める剥ぎ方をした").toBe(0);
  });

  it("当たりが減らん事 – 四十の語で『語 + 助詞』は常に其上", () => {
    const 語々 = [
      "機械学習",
      "セキュリティ",
      "ネットワーク",
      "高性能計算",
      "音声認識",
      "査読",
      "論文",
      "抄録",
      "締切",
      "学会",
      "研究会",
      "ワークショップ",
      "学生",
      "関西",
      "九州",
      "海外",
      "国内",
      "9月",
      "3月",
      "来年",
      "今年",
      "来週",
      "ポスター",
      "招待",
      "bibtex",
      "ics",
      "icassp",
      "sc",
      "人工知能",
      "半導体",
      "量子",
      "医療",
      "教育",
      "エネルギー",
      "robotics",
      "机械",
      "オンライン参加可",
      "A*",
      "ccf",
      "延長",
    ].map((語) => 語.trim());
    let 屆いた本 = 0;
    for (const 語 of 語々) {
      const 基 = 当たり(語);
      for (const 助詞 of ["だけ", "のみ", "しか"]) {
        const 今 = 当たり(`${語}${助詞}`);
        expect(今, `『${語}${助詞}』が『${語}』（${基} 行）より減つた`).toBeGreaterThanOrEqual(基);
        if (今 > 0) 屆いた本 += 1;
      }
    }
    /* 減る事は構造的に無い（剥いだ先は元の語の部分列）が、屆いた本數は實測で張る –
     * 直し前は此の内の殆どが 0 行だつた（上の一覽 – 其の語で行が出る物だけ數へる）。 */
    expect(
      屆いた本,
      "『語 + 限定の助詞』が一つも行に出會はなんだ – 目が効いてない",
    ).toBeGreaterThan(60);
    expect(收錄().length, "品書の行数が変わつた").toBe(3250);
  });
});
