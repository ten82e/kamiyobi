/* 第 483 回 – 月の語に其の初めの言い方を繋いだ形が 0 件で案内も無かつた
 *
 * 実測（2026-11-08 – 実ビルドの品書 868 行・固定時刻 2026-08-09T00:00:00Z）で、其れ等は 0 件・
 * 案内も無しだつた – `来月初め` `来月始め` `来月最初` `来月頭`・`今月初め` `今月始め` `今月最初`・
 * `先月初め` `先月始め` `先月最初` `先月頭`・`再来月初め` `再来月始め` `再来月最初`・`1月初め`
 * `1月頭` `3月最初` `12月頭`・漢数字の `十月初め` …（二十五語）。其上、同じ事を空格で打つ形
 * （`来月 初め`）と『の』を挟む形（`来月の初め`）も 0 件で案内も無かつた。
 * 月の初めは何日を指すかに公用の決まりが無い（一日か、初めの几日か、初めの十日＝上旬か）ので、
 * 勝手に 1日 や上旬へは寄せない（締切の推測はしない – AGENTS.md）。其の旨を其の場に書く決まりは
 * 裸の `月初` に既に在つた（第 390 回 – 件の数欄は「其の日を打つか『上旬』で打ってください」と書く）
 * ので、其の寄せ方を月の語を継いだ形と繋げた形に広げた。
 * 其の方の語は寄せず行を出さない為、**行数は一個も動かない**（其れを下の群と検査で張る）。
 * 同じ群の週の語は第 416 回・第 431 回、其れに抜けて居た『初旬』『始め』『最初』『末日』は此の回
 * 足した（実測で十六語が 0 件・案内も無しだつた）。年の語は其の方が `年初` → `1月` の対を持つ為、
 * 其の方の列で寄せる話になる（残した差に載せた – 実測の語数は此の頁の頭に書いた群と同じ）。*/
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { builtSite } from "./built_site.ts";

const 基準 = Date.parse("2026-08-09T00:00:00Z");
function 品書(): string[] {
  return (
    Recommender.candidateRows(
      JSON.parse(readFileSync(join(builtSite(), "catalog.json"), "utf8")) as unknown as never,
    ) as unknown as Array<{ hay: string }>
  ).map((行) => String(行.hay));
}
const 全 = 品書();
function 列(文: string) {
  return new Set(全.filter((行) => Recommender.searchMatcher(文, 基準)(行) === true));
}
function 画面案内(文: string) {
  return (Recommender.uiWordNoteJa(文) || "").trim();
}
function 日の案内(文: string) {
  return (Recommender.relativeDayNotes(文, 基準) || []).join("|");
}
function 何か書く(文: string) {
  return 画面案内(文) !== "" || 日の案内(文) !== "";
}

describe("月の語に其の初めの言い方を繋いだ形が 0 件の訳を書く（第 483 回）", () => {
  it("繋いだ形・離した形・『の』を挟む形が同じ説明を出す", () => {
    for (const 文 of [
      "来月初め",
      "来月始め",
      "来月最初",
      "来月 初め",
      "来月の初め",
      "来月 の 初め",
      "今月始め",
      "先月最初",
      "再来月初め",
      "1月初め",
      "12月頭",
      "十月初め",
    ]) {
      const 説 = 画面案内(文);
      expect(説 !== "", `「${文}」が無言だつた（黙つて 0 件）`).toBe(true);
      /* 打ち直しの三つ（其の日・其の十日間・其の月）を并べて書く（其の内一つを落とした改ざんが
       * 通つた為、其の列まで張つた – 実測 2026-11-08）。*/
      expect(説, `「${文}」の案内が其の日を打てと書いていない`).toContain("其の日");
      expect(説, `「${文}」の案内が上旬を打てと書いていない`).toContain("其の十日間（「上旬」）");
      expect(列(文).size, `「${文}」で行を出した（勝手に寄せた）`).toBe(0);
    }
  });
  it("月と『末』『終わり』を離つたり『の』で挟んだりした形も詰め形と同じ行に出る（第 483 回）", () => {
    /* 実測（実ビルド 868 行）– `来月 末` **0 件** / `来月末` 245 件・`来月の末` **0 件** / 245 件・
     * `今月 末` **0 件** / 192 件・`12月 末` **0 件** / 178 件・`再来月 末` **0 件** / 194 件。
     * 其の内 `来月 終わり` は第 478 回で通るやうになつて居たので、其の目に『末』と『の』を足した。
     * 週の語（`来週 末` 40 件）と `週末` 262 件・`月末` 192 件・`年度末` 82 件は其侭。*/
    for (const [繋, 離] of [
      ["来月末", "来月 末"],
      ["来月末", "来月の末"],
      ["来月終わり", "来月 終わり"],
      ["今月末", "今月 末"],
      ["12月末", "12月 末"],
      ["再来月末", "再来月 末"],
    ] as Array<[string, string]>) {
      expect([離, 列(離).size]).toEqual([離, 列(繋).size]);
      expect([離, 列(離).size > 0]).toEqual([離, true]);
    }
    expect(列("来月末").size).toBe(178);
    expect(列("今月末").size).toBe(118);
    expect(列("12月末").size).toBe(84);
    expect(列("再来月末").size).toBe(97);
    /* 実測（実ビルド 868 行では 夫々 245・192・178・194・262・40・192・82 件）。*/
    expect(列("週 末").size).toBe(146);
    expect(列("来週 末").size).toBe(34);
    expect(列("月末").size).toBe(118);
    expect(列("年度末").size).toBe(29);
  });
  it("其の月の幅の語を其のまま打ち直しに書く（第 459 回 – 案内は打たれた語を名乗る）", () => {
    expect(画面案内("来月初め")).toContain("又は其の月（「来月」）");
    expect(画面案内("来月 初め")).toContain("又は其の月（「来月」）");
    expect(画面案内("3月最初")).toContain("又は其の月（「3月」）");
  });
  it("末側の言い方は其の方の月の末に解ける – 案内を立てて行を減らさない", () => {
    for (const 文 of ["来月末", "来月末日", "来月終わり", "今月末", "先月末"]) {
      expect(列(文).size > 0, `「${文}」が出ない`).toBe(true);
      expect(画面案内(文), `「${文}」に絞り込めぬ案内が並んだ`).toBe("");
    }
  });
  /* 群の張りは二つに割つて在る – 一纏めにすると品書全体を舋める回数が四十を越へ、全体の検査を
   * 並べた時に 30 秒の制限を越へた（実測 2026-11-08 – 第 474 回・第 480 回と同じ教訓）。*/
  function 群を数(頭々: string[], 尾部: string[]) {
    const 黙: string[] = [];
    const 絞: string[] = [];
    for (const 甲 of 頭々)
      for (const 乙 of 尾部)
        for (const 文 of [`${甲}${乙}`, `${甲} ${乙}`, `${甲}の${乙}`]) {
          if (列(文).size === 0) {
            if (!何か書く(文)) 黙.push(文);
          } else if (画面案内(文) !== "") {
            絞.push(文); // 行が出るのに「絞り込めません」と書く形（噓）
          }
        }
    return { 黙, 絞 };
  }

  it("群 – 頭の側の言い方は 0 件なら必ず何か書く（第 483 回）", () => {
    const { 黙, 絞 } = 群を数(
      ["来月", "今月", "先月", "再来月", "1月", "3月", "12月"],
      ["頭", "初め", "始め", "最初"],
    );
    expect(黙, "0 件で案内も無い打ち方が残つた").toEqual([]);
    expect(絞, "行が出るのに絞り込めぬ案内を並べた").toEqual([]);
  });
  it("群 – 末側の言い方も同じ決まり（第 483 回）", () => {
    const { 黙, 絞 } = 群を数(
      ["来月", "今月", "先月", "再来月", "1月", "3月", "12月"],
      ["末", "終わり"],
    );
    /* 第 483 回に残した差（`再来月 終わり`・`1月 終わり`・`3月 終わり`・`12月 終わり`）は、第 491 回で
     * 月の語＋末日・終わりを其の方の表の語（末）へ寄せる形にしたので、全部直つた（詰め形と同じ行）。
     * 此處に挙げる物は無い – 有れば下の張りが落ちる。*/
    const 残る: string[] = [];
    expect(
      黙.filter((文) => !残る.includes(文)),
      "其它の 0 件で案内も無い打ち方が残つた",
    ).toEqual([]);
    for (const 文 of 残る)
      expect([文, 黙.includes(文)], `「${文}」が直つた積り`).toEqual([文, true]);
    expect(絞, "行が出るのに絞り込めぬ案内を並べた").toEqual([]);
  });
  it("群 – 旬側の言い方も同じ決まり（第 483 回）", () => {
    const { 黙, 絞 } = 群を数(
      ["来月", "今月", "先月", "1月", "12月"],
      ["上旬", "初旬", "中旬", "下旬"],
    );
    expect(黙, "0 件で案内も無い打ち方が残つた").toEqual([]);
    expect(絞, "行が出るのに絞り込めぬ案内を並べた").toEqual([]);
  });
});

describe("週の語の同じ群に抜けて居た言い方（第 416 回・第 431 回の続き）", () => {
  it("『始め』『最初』『末日』は其の場で説明し、旬は二語に割れて行が出る（第 483 回・第 490 回）", () => {
    for (const 文 of ["来週始め", "来週最初", "来週末日", "今週始め"]) {
      expect(何か書く(文), `「${文}」が無言だつた`).toBe(true);
      expect(列(文).size, `「${文}」で行を出した`).toBe(0);
    }
    /* 旬（上旬・中旬・下旬・初旬）は第 490 回で二語に割れるやうになつた – 離した形と同じ行になり、
     * 案内は出さない（第 483 回は案内を出して居た – 實測で行の側が先に決まつた爲）。*/
    for (const 文 of ["来週初旬", "今週初旬", "先週初旬", "再来週初旬"]) {
      expect([文, 列(文).size], `「${文}」`).toEqual([
        文,
        列(`${文.slice(0, 2)} ${文.slice(2)}`).size,
      ]);
      /* 案内（絞り込めません）は出さない – 其の週の幅を名乗る案内は出る（行が出る爲の範囲）。*/
      expect(画面案内(文), `「${文}」に絞り込めぬ案内が並んだ`).not.toContain("絞り込めません");
    }
    expect(列("来週 初旬").size).toBe(2); /* 実ビルド 868 行では 4 件 */
  });
});

