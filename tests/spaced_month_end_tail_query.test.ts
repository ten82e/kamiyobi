/**
 * 月のまとまりの語（`来月末` `年度末` `年度初め` `年明け`）と年度の語に幅の語尾（`中` `内`
 * `以内に`）を空格で離って付ける打ち方（第 465 回）。
 *
 * 実測（2026-11-07 – 実ビルドの品書 872 行・固定時刻 2026-08-09T00:00:00Z）で、詰め形は
 * 通るのに語と語尾の間に空格を入れただけで黙つて居た – `来月末` 240 行 / `来月 末` **0 行**・
 * `今月末` 189 行 / `今月 末` **0 行**・`月末` 189 行 / `月 末` **0 行**・`年度末` 80 行 /
 * `年度 末` **0 行**・`年度初め` 81 行 / `年度 初め` **0 行**・`年度当初` 81 行 /
 * `年度 当初` **0 行**・`年明け` 109 行 / `年 明け` **0 行**。年度の語に幅の語尾は語のかけ算
 * （AND）になつて**別な行に絞れて居た** – `年度中` 872 行 / `年度 中` 61 行・
 * `年度内` 872 行 / `年度 内` 38 行（件数欄は「年度 = 2026年4月1日〜2027年3月31日」と書くのに
 * 其の範囲の行が出て居ない – 第 332 回の噓）。
 *
 * 直しは第 462 回・第 463 回・第 464 回と同じ二段 – ① 幅の語尾の表に `末` `初め` `始め`
 * `当初` `明け` を入れる（其の方の語は月のまとまりの表 `PERIOD_MONTH_WORDS_JA` が受ける）。
 * ② 語の表に年度の目 `fiscalYearTermsJa` を一本足す。**測つて解ける語尾だけ**寄せる決まりは
 * 第 453 回と同じ – 詰め形が解けない語（`今年 末` は第 484 回で 84 行通る – 前 0 行。其れ以前の
 * 実測では詰め形 `今年末` も 0 行だつた）と、詰め形が
 * 別な語に化ける語（`年 中` – 詰め形 `年中` は 0 行）は寄せない。
 *
 * 此の頁の検査は同じ検査の品書（435 行）で測つた数を持つ（実ビルド 872 行とは違う – 第 442 回
 * の決まり。品の大きさは張らず、詰め形と空格形の対称差 0 を張る）。
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { builtSite } from "./built_site.ts";

const 基準 = Date.parse("2026-08-09T00:00:00Z");

/* 品の語は `candidateRows` が作った検索の語（`hay`）の文字列 – 照合は其の文字列に掛かる
 * （第 442 回 – 同じ検査のビルドで測つた行数を張る）。*/
function 品書(): string[] {
  return (
    Recommender.candidateRows(
      JSON.parse(readFileSync(join(builtSite(), "catalog.json"), "utf8")) as unknown as never,
    ) as unknown as Array<{ hay: string }>
  ).map((行) => String(行.hay));
}

const 全 = 品書();

function 列(query: string): Set<string> {
  const 当 = Recommender.searchMatcher(query, 基準);
  return new Set(全.filter((行) => 当(行) === true));
}

function 対称差(x: Set<string>, y: Set<string>): number {
  let 差 = 0;
  const 向 = new Set(y);
  for (const 物 of x) if (!向.has(物)) 差 += 1;
  const 帰 = new Set(x);
  for (const 物 of y) if (!帰.has(物)) 差 += 1;
  return 差;
}

describe("月のまとまりの語に幅の語尾を離って付けても詰め形と同じ行に出る（第 465 回）", () => {
  const 対: Array<[string, string, number]> = [
    ["来月 末", "来月末", 178],
    ["今月 末", "今月末", 118],
    ["月 末", "月末", 118],
    ["先月 末", "先月末", 11],
    ["来月 内", "来月内", 178],
    ["今月 内", "今月内", 118],
    ["年度 末", "年度末", 28],
    ["年度 初め", "年度初め", 29],
    ["年度 始め", "年度始め", 29],
    ["年度 当初", "年度当初", 29],
    ["年度 中", "年度中", 435],
    ["年度 内", "年度内", 435],
    ["年 明け", "年明け", 23],
    /* 第 463 回で開いた語尾の続き – 同じ目（月のまとまりの表）を受ける形 */
    ["来月 中", "来月中", 178],
    ["来週 中", "来週中", 43],
  ];
  for (const [空格, 詰め, 期待] of 対) {
    it(`「${空格}」は詰め形「${詰め}」と同じ ${期待} 行`, () => {
      /* 詰め形が其の方の品で一行以上引ける事 – 両側 0 行の空振りで対称差 0 を通さない。 */
      expect(列(詰め).size, 詰め).toBe(期待);
      expect(対称差(列(空格), 列(詰め)), `${空格} ⇔ ${詰め}`).toBe(0);
    });
  }

  it("語尾に `に` を足しただけの形も同じ行に出る", () => {
    expect(列("年度 以内に").size).toBe(435);
    expect(対称差(列("年度 以内に"), 列("年度以内に"))).toBe(0);
  });
});

describe("詰め形が解けない語尾は寄せない（第 453 回・第 462 回の決まり）", () => {
  /* 詰め形も 0 行の語は、寄せても 0 行のままなので門が通さない。 */
  const 不動: Array<[string, number]> = [
    ["今年 末", 0],
    /* 年の語に其の切れ目の語を直に繋いだ形は第 484 回で其の方の対に寄せるやうにした（前 0 行 –
     * `年末` 178 行・`年初` 99 行が通るのに継いだ形だけ黙つて居た）。*/
    ["今年末", 84],
    ["来年末", 21],
    ["ml 末", 0],
    ["ml末", 0],
    ["ml 初め", 0],
    ["ml明け", 0],
    ["論文 末", 0],
    ["論文末", 0],
    ["査読 末", 0],
    /* 詰め形 `年中` は 0 行 – 寄せたら 27 行が 0 行に後退するので寄せない（第 462 回）。 */
    ["年 中", 27],
    ["年中", 0],
    /* 詰め形 `年内中` は 0 行（第 463 回で断つた侭）。 */
    ["年内 中", 27],
    ["年内中", 0],
    /* 月初の決まりは無いので寄せない（第 390 回 – 案内側が「月初の決まりは無い」と書く）。 */
    ["月初", 0],
    ["月初め", 0],
    ["月初 め", 0],
    /* 相対日から開いた幅 – 第 475 回で `以降` 等を其の初日からの幅に解き、第 476 回で `から`
     * `より` も受けるやうにした（前 0 行で案内だけ「並びます」と書く形が残つて居た）。受けるのは
     * 二つの守りの内側 – ①打ち込みが其処で終る形、②後に其它の日の語が控へる形は三語を一語に継いで
     * 其の方の幅の機械に渡す（`明日 から 明後日` ⇔ `明日から明後日` – 第 373 回・第 455 回）。*/
    ["来週 から", 422],
    ["来週から", 422],
    ["来週 より", 422],
    /* `末` を語尾の表に足した事で別の機械が壊れて居ない事。 */
    ["来週 まで", 43],
    ["来週 いっぱい", 43],
    ["ml 中", 2],
    ["査読 中", 0],
    ["来月 下旬", 59],
    ["17時 まで", 0],
    ["17時まで", 0],
  ];
  for (const [打ち方, 期待] of 不動) {
    it(`「${打ち方}」は今まで通り ${期待} 行`, () => {
      expect(列(打ち方).size, 打ち方).toBe(期待);
    });
  }

  it("『週末』の言い換えは別の機械 – 語の表の目（七語の週）は広げず、別の段で寄せる（第 471 回）", () => {
    /* `週末` は曜日の言い換え表（`querySynonymMap`）が受ける語で、語の表の曜日の目は七語の週
     * （`来週` 等）だけを見て居る。七語の条件を緩めると測つて解ける目では無い目に緩む
     * （第 463 回 – 使はれない目は置かない）ので、七語の表は今も広がらない。
     * `週 末` が通るやうにしたのは第 471 回で – 文字列の書換の段（`複合語の切れ目`）で
     * 詰め形に寄せるだけで、此の表には手を入れて居ない（実測 2026-11-08 – 145 件 ⇔ 145 件）。*/
    expect(列("週末").size).toBe(145);
    expect(列("週 末").size).toBe(145);
    expect(列("来週末").size).toBe(34);
    expect(列("今週末").size).toBe(1);
    /* 七語の週に依らぬ形は依然として別の行 – 表が広かつて居ない事の実測 */
    expect(列("週 末日").size).toBe(0);
  });
});

describe("件数欄は寄せた形で解き、名乗りは打たれた侭にする（第 462 回・第 465 回）", () => {
  it("『年度 中』『年度 内』は年度の範囲を打たれた空格のまま名乗る", () => {
    for (const 語 of ["年度 中", "年度 内"]) {
      const 案内 = Recommender.relativeDayNotes(語, 基準).join("");
      expect(`${語} -> ${案内}`).toContain(`${語} = 2026年4月1日(水)〜2027年3月31日(水)の締切`);
      /* 行は其の範囲に絞れて居る – 「検索欄では絞り込まずにいます」は噓なので出してはいけない。*/
      expect(案内).not.toContain("絞り込まずにいます");
    }
  });

  it("『年度 以内に』も年度の範囲を書く（語尾の `に` は助詞として剥ぐ）", () => {
    const 案内 = Recommender.relativeDayNotes("年度 以内に", 基準).join("");
    expect(案内).toContain("2026年4月1日(水)〜2027年3月31日(水)の締切");
    expect(案内).not.toContain("絞り込まずにいます");
  });

  it("月のまとまりの語は詰め形と同じで案内を持たない – 黙つて居るのは噓では無い", () => {
    /* `来月末` `年度末` は其の方の表が歴月へ寄せる語で、件数欄の説明は持たない（第 352 回）。
     * 空格形も同じ沈黙 – 行数が詰め形と違う時にだけ案内が要る（第 332 回）。 */
    for (const 語 of ["来月 末", "年度 末", "年 明け"]) {
      expect(Recommender.relativeDayNotes(語, 基準), 語).toEqual([]);
    }
    expect(列("来月 末").size).toBe(178);
  });
});

