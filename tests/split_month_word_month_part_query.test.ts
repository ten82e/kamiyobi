import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { builtSite } from "./built_site.ts";

/* 月の語を二語に離つて打ち、其の後に上旬・中旬・下旬・最終週を続ける形（第 469 回）。
 * 実測（2026-11-07 – 実ビルドの品書 868 行・固定時刻 2026-08-09T00:00:00Z）で、行は其の月で
 * 絞れて居るのに件数欄は**今の月**の塊の範囲を書いて居た –
 * `9 月 下旬` 86 行に対し「下旬 = 2026年8月21日(金)〜8月31日(月)」、
 * `11 月 上旬` 86 行に対し「上旬 = 2026年8月1日(土)〜8月10日(月)」、
 * `3 月 最終週` 16 行に対し「最終週 = 2026年8月29日(土)〜8月31日(月)」。
 * 月の語を詰めて打つ `9月 下旬` は其の月に解けるので、空格の位置だけで噓か噓で無いかに
 * 分かれて居た（案内は画面に出る物なので、黙つても嘘でもいけない – 第 332 回）。
 * 287 語の群（空格の位置の総当り・その他の月・助字 `の`・分野語・対照）で行の差 0・案内の差 88 語。
 * 其の方の機械が解くかの確かめを継いだ形に一度だけ掛ける形に簡素化した – 其の語単体の確かめを
 * 先に足す版、継いだ語を解いた語から退ける pop を添えた版も、此處の 287 語と語を後へ続けた
 * 328 語で案内の文が一字も変わらなかつた（実測 2026-11-07 – 第 463 回 – 効かない目は載せない）。*/

const 基準 = Date.parse("2026-08-09T00:00:00Z");
function 品書(): string[] {
  return (
    Recommender.candidateRows(
      JSON.parse(readFileSync(join(builtSite(), "catalog.json"), "utf8")) as unknown as never,
    ) as unknown as Array<{ hay: string }>
  ).map((行) => String(行.hay));
}
const 全 = 品書();
function 列(query: string): Set<string> {
  const 当 = Recommender.searchMatcher(query, 基準);
  return new Set(全.filter((行) => 当(行) === true));
}
function 対称差(a: Set<string>, b: Set<string>): number {
  return [...a].filter((x) => !b.has(x)).length + [...b].filter((x) => !a.has(x)).length;
}
function 案内(query: string): string {
  return Recommender.relativeDayNotes(query, 基準).join("");
}

describe("空格の位置で行数が割れない（第 469 回）", () => {
  it("`9 月` + 塊の語は詰め形と一字も違はぬ行が出る", () => {
    for (const 幅 of ["上旬", "中旬", "下旬", "最終週", "最後の週"]) {
      const 詰 = 列(`9月${幅}`);
      for (const 前 of ["", " "])
        for (const 後 of ["", " "]) {
          const 打ち方 = `9${前}月${後}${幅}`;
          expect(対称差(列(打ち方), 詰), 打ち方).toBe(0);
        }
    }
  });
  it("件数欄は其の月の範囲を書き、今の月を書かない", () => {
    const 決まり: Array<[string, string, string]> = [
      ["9 月 下旬", "2026年9月21日(月)〜2026年9月30日(水)", "2026年8月21日"],
      ["9 月 上旬", "2026年9月1日(火)〜2026年9月10日(木)", "2026年8月1日"],
      ["9 月 中旬", "2026年9月11日(金)〜2026年9月20日(日)", "2026年8月11日"],
      ["9 月 最終週", "2026年9月29日(火)〜2026年9月30日(水)", "2026年8月29日"],
      ["9 月 最後の週", "2026年9月29日(火)〜2026年9月30日(水)", "2026年8月29日"],
    ];
    for (const [打ち方, 範囲, 今の月] of 決まり) {
      const 文 = 案内(打ち方);
      expect(文, 打ち方).toContain(範囲);
      expect(文, 打ち方).not.toContain(今の月);
    }
  });
});

describe("件数欄は打たれた語を名乗る（第 459 回・第 462 回）", () => {
  it("空格の位置そのままに名乗り、其の方の日付を書く", () => {
    expect(案内("9 月 下旬")).toContain("9 月 下旬 = 2026年9月21日(月)〜2026年9月30日(水)");
    expect(案内("9 月 上旬")).toContain("9 月 上旬 = 2026年9月1日(火)〜2026年9月10日(木)");
    expect(案内("12 月 上旬")).toContain("12 月 上旬 = 2026年12月1日(火)〜2026年12月10日(木)");
    expect(案内("9 月 最終週")).toContain("9 月 最終週 = 2026年9月29日(火)〜2026年9月30日(水)");
    /* 分け方の決まりも其の侭（下旬は月末まで） */
    expect(案内("9 月 下旬")).toContain("下旬は月の 21 日から 30 日までです（下旬は月末まで）");
  });
  it("月の語を詰めて打つ形は第 332 回の侭", () => {
    expect(案内("9月 下旬")).toContain("9月 下旬 = 2026年9月21日(月)〜2026年9月30日(水)");
    expect(案内("9月下旬")).toContain("9月下旬 = 2026年9月21日(月)〜2026年9月30日(水)");
    expect(案内("9 月下旬")).toContain("9 月下旬 = 2026年9月21日(月)〜2026年9月30日(水)");
  });
  it("助字 `の` を離つて打つ形も其の月の範囲を書く（名乗りは其の方で消える助字を復元しない）", () => {
    const 文 = 案内("9 月 の 下旬");
    expect(文).toContain("9 月 下旬 = 2026年9月21日(月)〜2026年9月30日(水)");
    expect(文).not.toContain("2026年8月");
  });
});

describe("その他の月と相対的な月（第 469 回）", () => {
  const 表: Array<[string, number, string]> = [
    ["9 月 下旬", 59, "2026年9月21日(月)"],
    ["9 月 上旬", 68, "2026年9月1日(火)"],
    ["9 月 中旬", 57, "2026年9月11日(金)"],
    ["9 月 最終週", 25, "2026年9月29日(火)"],
    ["12 月 上旬", 40, "2026年12月1日(火)"],
    ["12 月 中旬", 42, "2026年12月11日(金)"],
    ["12 月 下旬", 6, "2026年12月21日(月)"],
    ["3 月 下旬", 11, "2027年3月21日(日)"],
    ["1 月 上旬", 6, "2027年1月1日(金)"],
    ["2 月 下旬", 14, "2027年2月21日(日)"],
    ["5 月 下旬", 7, "2027年5月21日(金)"],
    ["来 月 下旬", 59, "2026年9月21日(月)"],
    ["来 月 中旬", 57, "2026年9月11日(金)"],
    ["先 月 下旬", 6, "2026年7月21日(火)"],
  ];
  it("行数と範囲の文が其の月に付く", () => {
    for (const [打ち方, 数, 初日] of 表) {
      expect(列(打ち方).size, 打ち方).toBe(数);
      expect(案内(打ち方), 打ち方).toContain(初日);
    }
  });
  it("過ぎた月の決まりも其の侭書く（第 332 回）", () => {
    expect(案内("先 月 下旬")).toContain("その範囲は過ぎています");
  });
  it("其の月に其の塊が在らない形は 0 行の侭で、今の月の塊として解く（第 467 回と同じ）", () => {
    expect(列("13 月 下旬").size).toBe(0);
    expect(案内("13 月 下旬")).toContain("下旬 = 2026年8月21日(金)");
  });
  it("月の語の無い形は今の月の侭（月を継がない）", () => {
    expect(列("月 下旬").size).toBe(58);
    expect(案内("月 下旬")).toContain("下旬 = 2026年8月21日(金)");
    expect(案内("の 下旬")).toContain("の 下旬 = 2026年8月21日(金)");
  });
  it("相対の月の語に助字を繋げた形は其の月の塊に寄せる（第 470 回 – 前は 0 行で黙つて居た）", () => {
    expect(案内("今 月の 下旬")).toContain("今月 下旬 = 2026年8月21日(金)");
    expect(案内("来 月の 下旬")).toContain("来月 下旬 = 2026年9月21日(月)");
    expect(列("今 月の 下旬").size).toBe(58);
    expect(列("来 月の 下旬").size).toBe(59);
  });
});

describe("継いだ形が其の方で解けない形の守り（第 453 回・第 389 回）", () => {
  it("其の月に其の塊が在らない形は黙らず、今の月の塊として書く", () => {
    expect(列("13 月 下旬").size).toBe(0);
    expect(案内("13 月 下旬")).toContain("下旬 = 2026年8月21日(金)");
    expect(列("2 月 第5週").size).toBe(0);
    expect(案内("2 月 第5週")).toContain("第5週 = 2026年8月29日(土)〜2026年8月31日(月)");
  });
  it("助字で繋がれたその他の語は月の語と取り違えない", () => {
    expect(列("ml の 下旬").size).toBe(3);
    expect(案内("ml の 下旬")).toContain("下旬 = 2026年8月21日(金)");
    expect(案内("令和8 年 下旬")).toContain("下旬 = 2026年8月21日(金)");
  });
  it("週の語に続けた塊の語は別々の文に書く（第 416 回）", () => {
    expect(列("来週 月 下旬").size).toBe(0);
    expect(案内("来週 月 下旬")).toContain("来週 = 2026年8月10日(月)〜8月16日(日)");
    expect(案内("来週 月 下旬")).toContain("下旬 = 2026年8月21日(金)");
  });
  it("塊の語を列挙・範囲で並べた形は其々別の文に書く（第 349 回）", () => {
    expect(案内("下旬 又は 上旬")).toContain("下旬 = 2026年8月21日(金)");
    expect(案内("下旬 又は 上旬")).toContain("上旬 = 2026年8月1日(土)");
    /* 範囲の形（`9 月 上旬 から 中旬`）は第 476 回で其の方の幅の機械が一語で読む形に継いだ –
     * 其の範囲で行が出る（実測 120 件 ⇔ 詰め形 `9月上旬から中旬` 120 件）。案内は幅その物を名乗り、
     * 旬を二つ別々に書く形では無くなる（其の形は行を出すので第 413 回と同じ決まり）。*/
    expect(列("9 月 上旬 から 中旬").size).toBe(120);
    expect(列("9 月 上旬 から 中旬").size).toBe(列("9月上旬から中旬").size);
  });
  it("後ろにその他の塊が続いても其処までは継がない（実測 0 行の侭 – 残した差）", () => {
    expect(列("9 月 下旬 第2週").size).toBe(0);
    const 文 = 案内("9 月 下旬 第2週");
    expect(文).toContain("9 月 下旬 = 2026年9月21日(月)");
    expect(文).toContain("第2週 = 2026年8月8日(土)");
  });
});

describe("其の方の語に寄せる目を続けた形（第 469 回）", () => {
  it("`まで` を離つて続けると今日の範囲と其の月の末日の範囲になる", () => {
    /* 実測（第 474 回）– 離つた `まで` は其の月の範囲に解ける（前 12 件 → 277 件）*/
    expect(列("9 月 下旬 まで").size).toBe(277);
    expect(案内("9 月 下旬 まで")).toContain("9月下旬まで = 2026年8月9日(日)〜9月30日(水)");
  });
  it("後ろにその他の語が続いても其の月の範囲を書く", () => {
    expect(列("9 月 下旬 に").size).toBe(59);
    expect(案内("9 月 下旬 に")).toContain("2026年9月21日(月)");
    expect(列("9 月 最終週 に").size).toBe(25);
    expect(案内("9 月 下旬 の 論文")).toContain("2026年9月21日(月)");
    expect(案内("2026 年 9 月 下旬")).toContain("2026年9月21日(月)");
    expect(案内("ml 9 月 下旬")).toContain("2026年9月21日(月)");
  });
});

