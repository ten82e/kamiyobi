    /* 第 475 回では `から` を载せなかつたが、それで 0 件＋案内の噓が残つた。第 476 回では
     * ①打ち込みが其処で終る形だけ受ける、②後に其它の日の語が控へる形は三語を一語に継いで
     * 幅の機械に渡す、の二つの守りで受ける（実測 – 422 件 ⇔ 422 件）。*/
    for (const 語 of ["来週 から", "来週 以降"] as const) {
      expect(列(語).size).toBe(422);
      expect(Recommender.relativeDayNotes(語, 基準), `「${語}」に案内が残つた`).toEqual([]);
    }
    expect(列("来週から").size).toBe(422);
