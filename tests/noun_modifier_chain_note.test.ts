/* 第 513 回 – 其の名前を連体の「の」で他のの説明に繋いだ文（`参加費無料の会議` `費用の安い会議` `査読中のもの`）
 *
 * 実測（2026-11-11 – 実ビルドの品書 868 行・固定時刻 2026-08-09T00:00:00Z）。これまでの回合
 *（第 503 回〜第 512 回）で語尾を繋いだ形は随處塞いだが、**研究者が実際に打ちさうな文**を二十文
 * 並べて數へると、その内の九文が 0 件で畫面の四つの案内の道を全て默つて居た –
 * `参加費無料の会議` `費用の安い会議` `ビザの情報` `招待講演の nomination` `査読中のもの`
 * `共催してもらえる会議` `学生セッションのある会議` `オンライン開催のAI会議` `国内で開催されるセキュリティ会議`。
 * 理由 – 照合は「其の名前で打ちが終る」か白一覧の語尾（第 505 回）が其の儘続く形だけを見るので、
 * **其の名 + `の` + 名詞** のやうに語が続くと外れる。單體（`参加費無料` `費用` `ビザ`）は案内が出る。
 * 印を持つ群の語 ×「の+名詞」を數へると 2 772 文の内 **2 321 文が 0 件で無言**だつた。
 *
 * 直しは連体の `の` で繋がれた形も受ける – 「其の欄はこの表に無い」といふ話は「の」で繋がれても
 * 同じなので応答は変はらない。ただし二つの門を付けた（実測で崩れた決まりを残す爲）:
 * - **語をまたがない時だけ** – `過去の締切 関西` `招待講演の nomination` のやうに、其后に
 *   空格・読点で他のの語が続く打ち方は「値を並べた打ち手」なので舊の決まり（第 250 回・第 354 回 –
 *   案内を被せない）が勝つ。此の門を外すと其の決まりを張つて居る二頁が落ちた（実測）。
 * - **助詞を挟まない他のの語の頭は弾く** – `費用対効果分析` `リアルタイム処理` `メジャーな学会`
 *  `対面について` は默つた侭（第 505 回・第 510 回の磁石の決まり）。
 *
 * 行は一個も動かして居ない（群 128 語で行の差 0 語・減 0 語・案内は無言→出る 64 語・消えた案内 0 語）。
 * 案内の道は三つの函數からしか呼ばれない（第 505 回で構造を確認済み）。
 *
 * 舊の張りのうち三處は此の決定で古くなつた – `オフラインの会議` `小規模な会議の会場` `査読期間の長さ`
 * `参加費の安い会議` を「磁石だから默る」と張つて居たが、之れ等は助詞を挟む連体なので**応じる方が正しい**
 *（第 505 回の磁石は `費用対効果分析` のやうに助詞の無い語の頭の事）。其の頁は新しい実測に合はせた。*/
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { builtSite } from "./built_site.ts";

const 基準 = Date.parse("2026-08-09T00:00:00Z");
function 品書(): string[] {
  return (
    Recommender.candidateRows(
      JSON.parse(readFileSync(join(builtSite(), "catalog.json"), "utf8")) as unknown as never,
    ) as unknown as Array<{ hay: string }>
  ).map((行) => String(行.hay));
}
const 全 = 品書();
const 件 = (文: string) =>
  全.filter((行) => Recommender.searchMatcher(文, 基準)(行) === true).length;
function 畫面の案内(文: string) {
  return [
    Recommender.columnQueryNoteJa(文) || "",
    Recommender.uiWordNoteJa(文) || "",
    Recommender.dayRangeNoteJa(文) || "",
    Recommender.wholeTableQueryNoteJa(文) || "",
    ...(Recommender.relativeDayNotes(文, 基準) || []),
  ]
    .map((値) => String(値).trim())
    .filter((値) => 値)
    .join(" ∥ ");
}

describe("連体の「の」で繋がれた文が其の群の導きを出す（第 513 回）", () => {
  it("費用・ビザ・招待講演・査読・規模・參加形式・過去の打ち方", () => {
    for (const [文, 語] of [
      ["参加費無料の会議", "参加費無料"],
      ["費用の安い会議", "費用"],
      ["ビザの情報", "ビザ"],
      ["招待講演の枠", "招待講演"],
      ["査読中のもの", "査読中"],
      ["査読期間の長さ", "査読期間"],
      ["小規模な会議の会場", "小規模な会議"],
      ["オフラインの会議", "オフライン"],
      ["対面の予定", "対面"],
      ["メジャーの会議", "メジャー"],
      ["過去の締切のもの", "過去の締切"],
    ] as Array<[string, string]>) {
      const 説 = 畫面の案内(文);
      expect(説 !== "", `「${文}」は無言だつた（黙つて 0 件）`).toBe(true);
      expect(説, `「${文}」の案内が其の名前を名乘つて居ない`).toContain(`「${語}」`);
      expect(件(文), `「${文}」で行が出た`).toBe(0);
      /* 応答は單體のそれと同じ話 – 「の」で繋がれたから新しい話を作つて居ない。*/
      const 單 = 畫面の案内(語);
      expect(單, `「${語}」の單體の案内が消えた`).not.toBe("");
      expect(説.replace(/「[^」]*」/g, "").slice(0, 18)).toBe(
        單.replace(/「[^」]*」/g, "").slice(0, 18),
      );
    }
  });
  it("語をまたぐ打ち方は默つた侭（値を並べた打ち手 – 第 250 回・第 354 回）", () => {
    /* 此の門を外すと、其の決まりを張つて居る頁が落ちる（第 513 回の実測 – 二頁）。*/
    for (const 文 of [
      "過去の締切 関西",
      "招待講演の nomination",
      "書き出し HPC",
      "印刷 関西",
      "使い方 関西",
    ]) {
      expect(件(文)).toBe(0);
      expect(畫面の案内(文), `「${文}」に案内が乘つた（并べ打ちの決まりを破つた）`).toBe("");
    }
  });
  it("磁石（助詞を挟まない他のの語の頭）は默つた侭", () => {
    for (const 文 of ["費用対効果分析", "リアルタイム処理", "メジャーな学会", "対面について"]) {
      expect(件(文)).toBe(0);
      expect(畫面の案内(文), `「${文}」に案内が乘つた（强奪）`).toBe("");
    }
    /* 助詞が語の途中に在るだけの形も拾はぬ（第 510 回の邊境）。*/
    for (const 文 of ["参加費はがき代", "ビザはどこでも必要", "ヘルプデスクの乗り"]) {
      expect(畫面の案内(文), `「${文}」に案内が乘つた`).toBe("");
    }
  });
  it("行が出る打ち手には何も被せない", () => {
    expect(件("関西")).toBe(6);
    expect(件("セキュリティ")).toBe(68);
    expect(件("国内")).toBe(38);
    expect(件("オンライン参加可")).toBe(20);
    expect(件("ランクA")).toBe(3);
    for (const 文 of ["関西", "セキュリティ", "国内", "オンライン参加可", "ランクA"]) {
      expect(畫面の案内(文), `「${文}」に案内が乘つた`).toBe("");
    }
  });
  it("第 503 回〜第 512 回の道と他のの実測は変へて居ない", () => {
    expect(畫面の案内("参加費はいくら")).toContain("参加費");
    expect(畫面の案内("使い方の締切")).toContain("見方のてびき");
    expect(畫面の案内("確定")).toContain("延伸や確定の印");
    expect(畫面の案内("当面の締切")).toContain("曖昧な幅では絞り込めません");
    expect(畫面の案内("祝日の期限")).toContain("祝日・休日");
    expect(畫面の案内("前期")).toContain("という区分はこの表が持っていません");
    expect(畫面の案内("三連休明け")).toContain("のように祝日・休日の名前で");
    expect(畫面の案内("週明け頃")).toContain("「週明け頃」");
    expect(畫面の案内("和暦 2026年")).toContain("和暦");
    expect(畫面の案内("対面の締切")).toContain("参加形式の言い方ですが");
    expect(畫面の案内("キーノートの締切")).toContain("キーノート");
    expect(畫面の案内("令和7年の締切")).toContain("2025年の締切");
    expect(畫面の案内("カテゴリ HPC")).toContain("欄の名前の言い方ですが");
    expect((Recommender.columnQueryNoteJa("分野 セキュリティ") || "").trim()).toContain(
      "「分野」は",
    );
    expect(件("年内")).toBe(424);
    expect(件("年末中")).toBe(84);
    expect(件("来月 末日")).toBe(178);
    expect(件("週 末")).toBe(145);
    expect(件("締切時刻")).toBe(180);
    expect(件("ml から")).toBe(0);
  });
});

describe("ビルド成果物に目が在る事（第 466 回 – 成果物だけの検査でも捕まへる）", () => {
  const 物 = readFileSync(join(builtSite(), "recommender.js"), "utf8");
  it("連体の規則は語をまたがぬ時に限る – 両方の條件が現れて居る", () => {
    expect(物).toContain('tail.startsWith("の")');
    expect(物).toContain("!/[\\s、，,]/.test(tail)");
    /* 第 505 回の白一覧と第 510 回の問いの語尾は其侭。*/
    expect(物).toContain('"の締切"');
    expect(物).toContain('"はいくら"');
  });
});
