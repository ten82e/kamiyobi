import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { builtSite } from "./built_site.ts";

/* 単位の語に助字 `の` を繋げて打ち、其の単位を数字や相対の頭から離って打つ形（第 470 回）。
 * 実測（2026-11-08 – 実ビルドの品書 868 行・固定時刻 2026-08-09T00:00:00Z）で、助字を離した側は
 * 通るのに単位に繋げた側はあらゆる語で黙つて居た – `8 月 の 締切` 195 行 / `8 月の 締切` **0 行**・
 * `来 月 の 締切` 206 行 / `来 月の 締切` **0 行**・`9 月 の 下旬` 86 行 / `9 月の 下旬` **0 行**・
 * `2026 年 の 締切` 643 行 / `2026 年の 締切` **0 行**・`8 日 の 締切` 48 行 / `8 日の 締切` **0 行**・
 * `来 週 の 締切` 50 行 / `来 週の 締切` **0 行**・`8 月 の` 216 行 / `8 月の` **0 行**。
 * 直し（文字列の書換で頭と単位を詰め、助字を離つた人の語列に揃える）を検査した実測は –
 * 2 458 語（頭 15 種・単位 6 種・後ろの語 7 種の総当りにその他の群を足した物）で **行の差 341 語
 * （其の全部が 0 行から通つた物）・行が減つた物 0 語**。其の方の語に繋げた打ち方（`8 月の締切`）も
 * 助字を離つた打ち方（`8 月 の 締切`）も同じ行に出る事を下の対称差の検査が張る。*/

const 基準 = Date.parse("2026-08-09T00:00:00Z");
function 品書(): string[] {
  return (
    Recommender.candidateRows(
      JSON.parse(readFileSync(join(builtSite(), "catalog.json"), "utf8")) as unknown as never,
    ) as unknown as Array<{ hay: string }>
  ).map((行) => String(行.hay));
}
const 全 = 品書();
function 列(query: string): Set<string> {
  const 当 = Recommender.searchMatcher(query, 基準);
  return new Set(全.filter((行) => 当(行) === true));
}
function 案内(query: string): string {
  return Recommender.relativeDayNotes(query, 基準).join("");
}

describe("助字を単位の語に繋げて打つ形（第 470 回）", () => {
  it("空格の位置で行数が割れない – 詰め形・助字を離つた形と同じ行に出る", () => {
    const 対 = [
      ["8 月の 締切", "8月の 締切"],
      ["8 月の締切", "8月の締切"],
      ["9 月の 下旬", "9月の下旬"],
      ["来 月の 締切", "来月の締切"],
      ["先 月の 締切", "先月の締切"],
      ["今 月の 中旬", "今月の中旬"],
      ["2026 年の 締切", "2026年の締切"],
      ["8 日の 締切", "8日の締切"],
      ["来 週の 締切", "来週の締切"],
      ["17 時の 締切", "17時の締切"],
      ["8 月の", "8月の"],
    ] as const;
    for (const [離, 詰] of 対) expect(列(離).size, `${離} ⇔ ${詰}`).toBe(列(詰).size);
    /* 助字を另の語として打つ人（第 458 回）とも同じ行 – 其の方の目は其侭通る。*/
    expect(列("8 月の 締切").size).toBe(列("8 月 の 締切").size);
    expect(列("9 月の 下旬").size).toBe(列("9 月 の 下旬").size);
    expect(列("来 月の 下旬").size).toBe(列("来 月 の 下旬").size);
  });
  it("件数欄は其の月の範囲を書き、今の月を書かない", () => {
    const 文 = 案内("9 月の 下旬");
    expect(文).toContain("2026年9月21日(月)〜2026年9月30日(水)");
    expect(文).not.toContain("2026年8月21日");
    expect(案内("8 月の 下旬")).toContain("2026年8月21日(金)〜2026年8月31日(月)");
    expect(案内("今 月の 中旬")).toContain("2026年8月11日(火)〜2026年8月20日(木)");
    expect(案内("来 月の 下旬")).toContain("2026年9月21日(月)〜2026年9月30日(水)");
    expect(案内("先 月の 下旬")).toContain("2026年7月21日(火)〜2026年7月31日(金)");
    expect(案内("9 月の 第2週")).toContain("2026年9月8日(火)〜2026年9月14日(月)");
    expect(案内("8 月の 第2週")).toContain("2026年8月8日(土)〜2026年8月14日(金)");
    expect(案内("来 月の第2週")).toContain("2026年9月8日(火)〜2026年9月14日(月)");
  });
  it("件数欄は助字を名乗らず、其の月の塊として名乗る（第 469 回 – 消えた助字は復元しない）", () => {
    expect(案内("9 月の 下旬")).toContain("9月 下旬 = 2026年9月21日(月)");
    expect(案内("来 月の 下旬")).toContain("来月 下旬 = 2026年9月21日(月)");
    expect(案内("先 月の 下旬")).toContain("先月 下旬 = 2026年7月21日(火)");
    expect(案内("8 月の 第2週")).toContain("8月 第2週 = 2026年8月8日(土)");
    expect(案内("9 月の 下旬")).not.toContain("の 下旬");
    /* 助字を另の語として打つ人は其の語列のまま名乗る（第 469 回の目）。*/
    expect(案内("9 月 の 下旬")).toContain("9 月 下旬 = 2026年9月21日(月)");
  });
  it("行数の実測（固定ハーネスの品書 435 行 – 実ビルド 868 行と同じ形）", () => {
    expect(列("8 月の 締切").size).toBe(114);
    expect(列("9 月の 下旬").size).toBe(59);
    expect(列("来 月の 下旬").size).toBe(59);
    expect(列("先 月の 下旬").size).toBe(6);
    expect(列("今 月の 中旬").size).toBe(55);
    expect(列("2026 年の 締切").size).toBe(369);
    expect(列("8 日の 締切").size).toBe(20);
    expect(列("来 週の 締切").size).toBe(43);
    expect(列("1 月の 会議").size).toBe(23);
    expect(列("9 月の").size).toBe(179);
    expect(列("来 月の").size).toBe(178);
    expect(列("8 月の 第2週").size).toBe(26);
    expect(列("来 月の第2週").size).toBe(31);
  });
  it("後ろにその他の語を続けても其の月の範囲を書く", () => {
    expect(列("2026 年 9 月の 下旬").size).toBe(59);
    expect(列("ml 9 月の 下旬").size).toBe(6);
    expect(案内("ml 9 月の 下旬")).toContain("9月 下旬 = 2026年9月21日(月)");
    /* `まで` を離つた形は第 474 回で其の月の範囲として解ける（前 12 件 → 277 件 –
     * 前の 12 件は `9月` と `下旬まで`（今の月）の積だつた）。*/
    const 文 = 案内("9 月の 下旬 まで");
    expect(列("9 月の 下旬 まで").size).toBe(277);
    expect(文).toContain("9月下旬まで = 2026年8月9日(日)〜9月30日(水)");
  });
  it("助字の後ろにその他の語を空格無しで続ける形も其の方の語が割れる（詰め後の空格の実測）", () => {
    /* 寄せた形に後ろの語を続ける空格を落とすと、実測で `8 日の締切` 48 行 → 0 行・
     * `2026 年の締切` 643 行 → 0 行・`1 月の会議` 99 行 → 0 行・`9 月の下旬 まで` 19 行 → **419 行**
     * （月語とその他の語が一語に癒合して幅の目から外れる為 – 実ビルド 868 行 2026-11-08）。*/
    expect(列("8 日の締切").size).toBe(20);
    expect(列("8 日の締切").size).toBe(列("8 日の 締切").size);
    expect(列("2026 年の締切").size).toBe(369);
    expect(列("1 月の会議").size).toBe(23);
    expect(列("8 月の締切").size).toBe(114);
    expect(列("9 月の第2週").size).toBe(31);
    expect(案内("9 月の第2週")).toContain("9月 第2週 = 2026年9月8日(火)〜2026年9月14日(月)");
    expect(案内("17 時の締切")).toContain("17時 = 17:00〜17:59");
  });
  it("助字の後ろに幅の語を続ける形は其の月までの幅に絞る（寄せた後の幅の実測）", () => {
    expect(列("9 月の下旬 まで").size).toBe(277);
    expect(案内("9 月の下旬 まで")).toContain("9月下旬まで = 2026年8月9日(日)〜9月30日(水)");
    expect(列("来 月の下旬 まで").size).toBe(276);
    expect(案内("来 月の下旬 まで")).toContain("来月下旬まで = 2026年8月9日(日)〜9月30日(水)");
    expect(案内("来 月の下旬")).toContain("来月 下旬 = 2026年9月21日(月)");
    expect(案内("昨 月の下旬")).toContain("昨月 下旬 = 2026年7月21日(火)");
  });
});

describe("寄せない形の守り（第 453 回・第 470 回）", () => {
  it("月の語を単体で打つ形は寄せない – 何の月か決まらない", () => {
    expect(列("月の 下旬").size).toBe(0);
    expect(案内("月の 下旬")).toContain("下旬 = 2026年8月21日(金)");
    expect(列("月の 締切").size).toBe(0);
    expect(列("月 の 下旬").size).toBe(58);
  });
  it("漢数字の月・日を離つた頭も算用数字に寄せる（第 482 回 – 前の値 0 行だつた）", () => {
    /* 前はこの二つが 0 行だつた – 其の方の数字の目が漢数字と単位が繋がれて居る形だけ見て居た為
     * （`一 月の 下旬` **0 行** ⇔ `1 月の 下旬` 11 行）。月と日に限り空格を受ける目を足したので、
     * 助詞が後に離れて居る形も同じ行に出る。其の方の案内（下旬の語）は其侭出る。*/
    expect(列("一 月の 下旬").size).toBe(11); /* 実ビルド 868 行では 43 件 */
    expect(列("一 月の 下旬").size).toBe(列("1 月の 下旬").size);
    /* 日の語は其の日に出るが、其它の語（出費）が此の品書に在らんので 0 件の侭 –
     * 其の方の語が割れた事が案内に出る（「一 日 = …」）。*/
    expect(列("一 日の 出費").size).toBe(0);
    expect(列("一 日の 出費").size).toBe(列("1 日の 出費").size);
    /* 其の方の月が解けたので、下旬は其の月の下旬になる（前はこの月と取り違へて居た – 第 482 回）。*/
    expect(案内("一 月の 下旬")).toContain("2027年1月21日(木)〜2027年1月31日(日)");
  });
  it("分野語に付く助字は其侭 – 語を割つて行を増やさない", () => {
    expect(列("論文の 下旬").size).toBe(51);
    expect(案内("論文の 下旬")).toContain("下旬 = 2026年8月21日(金)");
    expect(列("ml の 下旬").size).toBe(3);
    expect(列("もの").size).toBe(0);
    expect(列("こと").size).toBe(0);
    expect(列("日の出").size).toBe(0);
  });
  it("その他の群 – 月の並べ・週末日・詰め形を踏んぢゃらない", () => {
    expect(列("8 月 と 9 月").size).toBe(284);
    expect(列("週末").size).toBe(145);
    expect(列("9月の下旬").size).toBe(59);
    expect(列("来月の下旬").size).toBe(59);
    expect(列("来月 の 下旬").size).toBe(59);
    expect(案内("昨 月の下旬")).toContain("2026年7月21日(火)〜2026年7月31日(金)");
    expect(列("17時の締切").size).toBe(0);
    expect(案内("17 時の 締切")).toContain("17時 = 17:00〜17:59");
  });
});

