/* 第 460 回 – 月の第何週を示す語の冠 `第` を空格で離って打つ人が、詰めて打つ人と
 * 同じ行・同じ案内に届くようにした（`第 2 週` `8 月 第 2 週` `来月 第 1 週` `第 二 週` 等）。
 * 実測（2026-11-05 – 実ビルドの品書 872 行・固定時刻 2026-08-09T00:00:00Z）:
 * 詰め形も月と週の間の空格も通る（`第2週` 34 行・`8月第2週` 34 行・`8月 第2週` 34 行・
 * `3月第1週` 15 行・`来月第1週` 60 行・`先月第3週` 16 行・`今月第4週` 50 行・`第5週` 37 行・
 * `8月第二週` 34 行）のに、冠の後ろに空格を打つただけの `第 2 週` `8 月 第 2 週`
 * `3 月 第 2 週` `来月 第 1 週` `先月 第 3 週` `今月 第 4 週` `第 5 週` `第 二 週`
 * `8 月 第 2 週 の 締切` は**0 行・案内も無し**だつた – 数字と `週` は寄るが、其の方の語の
 * 形の表（第〜週）が冠を含んだ形しか見ないので、冠だけが其の侭残る為（第 438 回・第 439 回で
 * 作った語の続きの穴）。実測値を張るのは検査用ビルドの品書（tests/built_site.ts – 435 行）–
 * 実ビルド（872 行）とは行数が違うので、詰め形との対称差 0 と共に其の方で測つた行数を張る
 * （第 455 回の流儀）。 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { builtSite } from "./built_site.ts";

const 基準 = Date.parse("2026-08-09T00:00:00Z");
const 品 = (
  Recommender.candidateRows(
    JSON.parse(readFileSync(join(builtSite(), "catalog.json"), "utf8")) as unknown as never,
  ) as unknown as Array<{ hay: string }>
).map((行) => String(行.hay));

function 列(語: string): Set<string> {
  return new Set(品.filter((行) => Recommender.searchMatcher(語, 基準)(行) === true));
}

function 対称差(a: Set<string>, b: Set<string>): number {
  return [...a].filter((k) => !b.has(k)).length + [...b].filter((k) => !a.has(k)).length;
}

function 案内(語: string): string {
  return Recommender.relativeDayNotes(語, 基準).join(" ");
}

describe("冠を離って打つ月の第何週が詰め形と同じ行に出る（第 460 回）", () => {
  /* [離って打つ形, 詰めた形, 検査用ビルドの品書で測つた行数] */
  const 形: Array<[string, string, number]> = [
    ["第 2 週", "第2週", 26],
    ["第 二 週", "第二週", 26],
    ["8 月 第 2 週", "8月第2週", 26],
    ["8 月 第 二 週", "8月第二週", 26],
    ["3 月 第 1 週", "3月第1週", 8],
    ["来月 第 1 週", "来月第1週", 48],
    ["先月 第 3 週", "先月第3週", 2],
    ["今月 第 4 週", "今月第4週", 30],
    ["第 5 週", "第5週", 26],
    ["第 2 週 です", "第2週です", 26],
    ["8 月 第 2 週 の 締切", "8月第2週の締切", 26],
  ];

  for (const [離した形, 詰め形, 期待] of 形) {
    it(`「${離した形}」は「${詰め形}」と同じ行が出て ${期待} 行`, () => {
      const 離 = 列(離した形);
      const 詰 = 列(詰め形);
      expect(対称差(離, 詰), `対称差が出た: ${離した形} ⇔ ${詰め形}`).toBe(0);
      /* 詰め形が実質の行を引いて居る事（空振りの対称差 0 を防ぐ – 第 455 回）。 */
      expect(詰.size, `詰め形が ${期待} 行で無い: ${詰め形}`).toBe(期待);
      expect(離.size, `離って打つ形が ${期待} 行で無い: ${離した形}`).toBe(期待);
    });
  }

  it("月と週の間にだけ空格を置く形は第 439 回の侭通る", () => {
    expect(対称差(列("8月 第2週"), 列("8月第2週"))).toBe(0);
    expect(列("8月 第2週").size).toBe(26);
  });
});

describe("件数欄は其の方の語を名乗り、引いた範囲を書く（第 460 回）", () => {
  it("冠を離つた形も『第2週は月の 8 日から 14 日までです』を添える", () => {
    /* 行だけ増えて案内が黙つて居ると、利用者は何の範囲を引いたのか読めない（第 332 回）。 */
    expect(案内("第 2 週")).toContain("第 2 週 = 2026年8月8日(土)〜2026年8月14日(金)の締切");
    expect(案内("第 2 週")).toContain("第2週は月の 8 日から 14 日までです");
    expect(案内("第 二 週")).toContain("第 二 週 = 2026年8月8日(土)〜2026年8月14日(金)の締切");
    expect(案内("第 二 週")).toContain("第二週は月の 8 日から 14 日までです");
  });

  it("月を別に打つ形は其の月の範囲を書く（今の月の範囲を書かない – 嘘になる）", () => {
    /* 検索側は其の方の週を其の月で解くので、案内も其の方に従ふ。実測で此れを置かなかつた
     * 間は `3 月 第 2 週`（12 行）に対して「2026年8月8日〜8月14日」と書いて居た。 */
    expect(案内("来月 第 2 週")).toContain("来月 第 2 週 = 2026年9月8日(火)〜2026年9月14日(月)");
    expect(案内("来月 第 2 週")).not.toContain("第 2 週 = 2026年8月");
    expect(案内("3 月 第 2 週")).toContain("3 月 第 2 週 = 2027年3月8日(月)〜2027年3月14日(日)");
    expect(案内("8 月 第 2 週")).toContain("8 月 第 2 週 = 2026年8月8日(土)〜2026年8月14日(金)");
    /* 詰め形が名乗つた語を、離した形も打たれた空格の侭名乗る（第 459 回）。 */
    expect(案内("来月第2週")).toContain("来月第2週 = 2026年9月8日(火)〜2026年9月14日(月)");
  });
});

describe("作らない幅・触らない語（測つた断り）", () => {
  it("第6週以上・第0週・其の月に在らない週は作らない（第 438 回）", () => {
    expect(列("第 6 週").size).toBe(0);
    expect(対称差(列("第 6 週"), 列("第6週"))).toBe(0);
    expect(列("第 0 週").size).toBe(0);
    expect(対称差(列("第 0 週"), 列("第0週"))).toBe(0);
  });

  it("語を続けた形を勝手に切らない（`第 2 週 目`・`第 2 週 から` は詰め形と同じ 0 行）", () => {
    /* 其の方の語は其の日までの幅を決まつた物 – `から` `目` を足した形を解くと幅を推す事に
     * なるので作らない（締切の推測はしない）。 */
    expect(対称差(列("第 2 週 目"), 列("第2週目"))).toBe(0);
    expect(列("第2週目").size).toBe(0);
    expect(対称差(列("第 2 週 から"), 列("第2週から"))).toBe(0);
    expect(列("第2週から").size).toBe(0);
    /* 週の語を二つ並べた列挙は解かない（第 395 回と同じ断り – 詰め形も 0 行）。 */
    expect(対称差(列("第 2 週 と 第 3 週"), 列("第2週と第3週"))).toBe(0);
    expect(列("第2週と第3週").size).toBe(0);
  });

  it("冠が其它の語に続く形は触らない（`第 2 ラウンド` – 其の方の表に無い語）", () => {
    expect(対称差(列("第 2 ラウンド"), 列("第2ラウンド"))).toBe(0);
    expect(列("第 2 ラウンド").size).toBe(16);
  });

  it("第 438 回・第 439 回の形と其它の相対的な日の語は無傷", () => {
    for (const [空格, 詰め] of [
      ["8 月 下旬", "8月下旬"],
      ["来月 下旬", "来月下旬"],
      ["8 月 22 日", "8月22日"],
      ["来週 の 締切", "来週の締切"],
      ["ml で", "mlで"],
    ] as Array<[string, string]>) {
      expect(対称差(列(空格), 列(詰め)), `対称差が出た: ${空格} ⇔ ${詰め}`).toBe(0);
    }
    expect(列("8月下旬").size).toBe(58);
    expect(列("来週").size).toBe(43);
    expect(列("上旬").size).toBe(10);
    /* 裸の `週`・`目`・冠だけでは何も絞らない（語の断片を語として扱わない）。 */
    expect(列("週").size).toBe(0);
  });

  it("残した差 – 詰め形の方が壊れて居る形は寄せない（`来週第2週` 0 行）", () => {
    /* 離つた形は来週と第2週の両方で絞れる（25 行）が、詰めた `来週第2週` は其の方の機械が
     * 語として解かず 0 行 – 詰め形を 0 行へ後退させる事は出来無いので其侭（第 458 回の断り
     * と同じ理由）。詰め形側を解くのは別の作業。 */
    expect(列("来週第2週").size).toBe(0);
    expect(列("来週 第 2 週").size).toBe(25);
  });
});

describe("直した形がビルド成果物に残る（第 460 回）", () => {
  const 物 = readFileSync(join(builtSite(), "recommender.js"), "utf8");

  it("冠を週の語に寄せる目が数字と漢数字の両方を見ている", () => {
    expect(物.split('prev === "第" &&').length - 1).toBe(1);
    expect(物.split("/^[0-9〇一二三四五六七八九十]{1,2}$/").length - 1).toBeGreaterThanOrEqual(1);
    /* 寄せた形が其の方の語の表に在る時だけ寄せる（第 453 回と同じ決まり）。 */
    /* 正規表現で数える – 字列として書くと整形器が「テンプレートの穴」だと言うので（第 460 回）。*/
    expect(物.match(/週的形状Ja\.test\(`第\$\{token\}\$\{次々\}`\)/g)?.length).toBe(1);
  });

  it("件数欄も冠を離した形を解き、月を別に打つ形まで見る", () => {
    expect(物.split('前々.解 === "第"').length - 1).toBe(1);
    expect(物.split("月の解の続き").length - 1).toBeGreaterThanOrEqual(3);
  });
});
