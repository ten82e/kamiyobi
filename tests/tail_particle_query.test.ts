/* 第 459 回 – 語の末尾に助詞を繋げて打つ人が、其の語だけで打つ人と同じ行に届くようにした
 * （`mlで` `機械学習で` `aiに` `セキュリティの` `関西で` `国内で` `研究会で` `査読が` 等）。
 * 実測（2026-11-05 – 実ビルドの品書 872 行・固定時刻 2026-08-09T00:00:00Z）:
 * 語その物は通る（`機械学習` 81 行・`論文` 461 行・`ml` 99 行・`ai` 331 行・
 * `セキュリティ` 152 行・`関西` 6 行・`国内` 38 行・`研究会` 23 行・`査読` 13 行・
 * `オンライン` 24 行）のに、助詞を繋いだだけで **全部 0 行・案内も無し**だつた –
 * `機械学習で` `論文で` `mlで` `aiに` `AIも` `セキュリティの` `関西で` `国内で`
 * `研究会で` `査読が` `オンラインで` いづれも 0 行。助詞の表（QUERY_PARTICLE_SPLIT_CHARS）
 * にこれらの字は在るが、語の末尾に付くと割れて残る語が一つになるので割れた語を採用する
 * 検査で捨てられて居た（第 419 回の `を` `と` `へ` と同じ穴）。
 * 第 419 回の守りは其侭 – 平仮名だけの語は剥がない（『きょうと』『しまね』）、残りが
 * 一字になる剥ぎ方はしない（『際に』）、暦日の幅の `まで`（第 398 回）と日付の語の語尾の
 * 表が受ける形（`明日中に` `3日以内に` – 件数欄が打たれた語を名指す）は剥がない。
 * 実測値を張るのは検査用ビルドの品書（tests/built_site.ts – 435 行）– 実ビルド（872 行）と
 * は行数が違うので、語その物との対称差 0 と共に、其の方で測つた行数を張る（第 455 回）。 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import Recommender from "../site/recommender.ts";
import { builtSite } from "./built_site.ts";

const 基準 = Date.parse("2026-08-09T00:00:00Z");
const 品 = (
  Recommender.candidateRows(
    JSON.parse(readFileSync(join(builtSite(), "catalog.json"), "utf8")) as unknown as never,
  ) as unknown as Array<{ hay: string }>
).map((行) => String(行.hay));

function 列(語: string): Set<string> {
  return new Set(品.filter((行) => Recommender.searchMatcher(語, 基準)(行) === true));
}

function 対称差(a: Set<string>, b: Set<string>): number {
  return [...a].filter((k) => !b.has(k)).length + [...b].filter((k) => !a.has(k)).length;
}

function 案内(語: string): string {
  return [
    Recommender.querySynonymNotes(語).join(" "),
    Recommender.uiWordNoteJa(語),
    Recommender.relativeDayNotes(語, 基準).join(" "),
  ]
    .filter((文) => 文)
    .join(" / ");
}

describe("語の末尾に助詞を繋いだ打ち方が語その物と同じ行に出る（第 459 回）", () => {
  /* [助詞を繋いだ打ち方, 語その物, 検査用ビルドの品書で測つた行数] */
  const 形: Array<[string, string, number]> = [
    ["mlで", "ml", 18],
    ["mlを", "ml", 18],
    ["mlと", "ml", 18],
    ["mlや", "ml", 18],
    ["mlも", "ml", 18],
    ["mlに", "ml", 18],
    ["mlは", "ml", 18],
    ["mlが", "ml", 18],
    ["aiで", "ai", 163],
    ["aiに", "ai", 163],
    ["aiは", "ai", 163],
    ["aiが", "ai", 163],
    ["aiも", "ai", 163],
    ["aiや", "ai", 163],
    ["HPCで", "HPC", 87],
    ["NLPを", "NLP", 3],
    ["セキュリティで", "セキュリティ", 68],
    ["セキュリティの", "セキュリティ", 68],
    ["国内で", "国内", 38],
    ["国内の", "国内", 38],
    ["関西で", "関西", 6],
    ["研究会で", "研究会", 23],
    ["論文で", "論文", 264],
    ["論文の", "論文", 264],
    ["機械学習で", "機械学習", 1],
    ["オンラインで", "オンライン", 20],
    ["23:59で", "23:59", 181],
    ["年内で", "年内", 424],
    ["午後で", "午後", 191],
    ["三日以内で", "三日以内", 7],
    ["来週木曜で", "来週木曜", 5],
  ];

  for (const [助詞を繋いだ形, 語その物, 期待] of 形) {
    it(`「${助詞を繋いだ形}」は「${語その物}」と同じ行が出て ${期待} 行`, () => {
      const 繋いだ = 列(助詞を繋いだ形);
      const 素 = 列(語その物);
      expect(対称差(繋いだ, 素), `対称差が出た: ${助詞を繋いだ形} ⇔ ${語その物}`).toBe(0);
      /* 詰め形が実質の行を引いて居る事（空振りの対称差 0 を防ぐ – 第 455 回）。 */
      expect(素.size, `語その物が ${期待} 行で無い: ${語その物}`).toBe(期待);
      expect(繋いだ.size, `助詞を繋いだ形が ${期待} 行で無い: ${助詞を繋いだ形}`).toBe(期待);
    });
  }

  it("語として離した助詞も末尾で立てば同じ（第 458 回の目を語の末尾に広げた）", () => {
    for (const [空格, 詰め] of [
      ["ml で", "mlで"],
      ["ml の", "mlで"],
      ["ai で", "aiで"],
      ["国内 で", "国内で"],
      ["第 2 ラウンドで", "第2ラウンドで"],
    ] as Array<[string, string]>) {
      expect(対称差(列(空格), 列(詰め)), `対称差が出た: ${空格} ⇔ ${詰め}`).toBe(0);
    }
    expect(列("ml で").size).toBe(18);
    expect(列("第2ラウンドで").size).toBe(16);
    expect(対称差(列("第 2 ラウンドで"), 列("第2ラウンド"))).toBe(0);
  });

  it("語の頭で立つ助詞の語は其侭（語その物を打った人の当たりを変へない – 第 458 回）", () => {
    expect(列("の").size).toBe(175);
    expect(列("で").size).toBe(78);
    /* 前の語に続く形だけ落とす – 語の頭の `の` は其侭残るので詰め形とは別物（残した差）。 */
    expect(列("の 締切").size).toBe(151);
    expect(列("の締切").size).toBe(0);
  });
});

describe("剥がないと決めた形（測つた断り）", () => {
  it("暦日の幅の `まで` を剥がない（期日が消える – 第 398 回・締切の推測はしない）", () => {
    /* 一文字剥ぐと `12月31日まで` が其の日だけになる – 実測で幅 422 行が 2 行に化けた。 */
    expect(列("12月31日まで").size).toBe(422);
    expect(対称差(列("12 月 31 日 まで"), 列("12月31日まで"))).toBe(0);
    expect(列("12月31日").size).toBeLessThan(10);
    /* `までに` は剥いだ先の `まで` が同じ幅なので受ける。 */
    expect(対称差(列("12月31日までに"), 列("12月31日まで"))).toBe(0);
    expect(対称差(列("来週までに"), 列("来週まで"))).toBe(0);
  });

  it("日付の語の語尾の表が受ける形は其の案内の侭（`明日中に` `3日以内に`）", () => {
    /* 其の側の規則が打たれた語を名指して件数欄に幅を書くので、剥ぐと案内が消える（実測）。 */
    expect(案内("明日中に")).toContain("明日中に = ");
    expect(案内("3日以内に")).toContain("3日以内に = ");
    expect(対称差(列("明日中に"), 列("明日中"))).toBe(0);
    expect(対称差(列("今週中で"), 列("今週中"))).toBe(0);
    expect(列("今週中").size).toBe(4);
    expect(対称差(列("8月の"), 列("8月"))).toBe(0);
    expect(列("8月").size).toBe(118);
    expect(対称差(列("来週で"), 列("来週"))).toBe(0);
    expect(列("来週").size).toBe(43);
    expect(列("上旬で").size).toBe(10);
  });

  it("平仮名だけの語と一文字で了う語は剥がない（第 417 回・第 419 回）", () => {
    /* 『きょうと』は京都の行が出る語 – `と` を剥いだ『きょう』にしない（割れた語を採る
     * 検査が守つて居た物と同じ穴）。 */
    expect(列("きょうと").size).toBe(2);
    expect(列("しまね").size).toBe(1);
    /* 語その物が助詞の打ち方は空の検索語にしない（第 417 回）。 */
    expect(列("です").size).toBe(0);
  });

  it("第 458 回の空格の助詞・第 457 回の空格列挙・第 456 回の空格暦日は其侭通る", () => {
    for (const [空格, 詰め] of [
      ["論文 の 締切", "論文の締切"],
      ["8 月 の 締切", "8月の締切"],
      ["8 月 は 締切", "8月は締切"],
      ["国内 の 会議", "国内の会議"],
      ["ml の 会議", "mlの会議"],
      ["来週 の 締切", "来週の締切"],
      ["8 月 と 9 月", "8月と9月"],
      ["12 月 31 日 まで", "12月31日まで"],
      ["12 月 24 日 の までに", "12月24日までに"],
    ] as Array<[string, string]>) {
      expect(対称差(列(空格), 列(詰め)), `対称差が出た: ${空格} ⇔ ${詰め}`).toBe(0);
    }
    expect(列("論文の締切").size).toBe(264);
    expect(列("8月と9月").size).toBe(284);
  });

  it("在ら無い日は寄せない（締切の推測はしない – 第 456 回）", () => {
    expect(列("4 月 31 日").size).toBe(0);
    expect(列("4 月 31 日 の").size).toBe(0);
    expect(列("2 月 30 日 で").size).toBe(0);
  });
});

describe("直した形がビルド成果物に残る（第 459 回）", () => {
  const 物 = readFileSync(join(builtSite(), "recommender.js"), "utf8");

  it("語尾の助詞の広い表が 1 箇所（`か` `な` `よ` `ね` を入れて居ない – 第 417 回）", () => {
    const 一行 = 物.split("\n").filter((行) => 行.includes("const 語尾の助詞Ja ="));
    expect(一行.length).toBe(1);
    expect(一行[0]).toContain("(?:で|に|は|が|も|の|や)");
    /* 一文字の終助詞は入れて居ない（第 417 回 – 語その物を壊す）。 */
    for (const 字 of ["か", "な", "よ", "ね"]) expect(一行[0]).not.toContain(`|${字}`);
  });

  it("暦日の幅の語尾を守る番が二つ在る（語の表と語尾の連なり – 第 398 回・第 459 回）", () => {
    /* 語の形が決まつている幅（`年内まで`）は日付の語の語尾の表が、位を付けた日
     * （`10日までに`）・記号で書いた幅（`8/20から8/25まで`）・時刻（`17時まで`）は
     * 語尾の連なりの表が受ける – 実測で下の番だけを外すと 43 本の検査が落ちた。 */
    expect(物.split("const 幅の語尾Ja = /(?:までに|まで|なので|のに|ので)").length - 1).toBe(1);
    const 表 = 物.slice(物.indexOf("const DATE_TOKEN_TAILS_JA = ["));
    expect(表.slice(0, 120)).toContain('"までに"');
    expect(表.slice(0, 160)).toContain('"まで"');
  });

  it("日付の語の語尾の表が受ける形を剥がない守りが 1 箇所", () => {
    expect(物.split('dateTokenStemJa(文) === ""').length - 1).toBe(1);
  });

  it("助詞の語を落とす目が語の頭だけを断つている（前の語が要る – 第 458 回・第 459 回）", () => {
    expect(物.split("番 > 0 &&").length - 1).toBeGreaterThanOrEqual(1);
    /* 語の末尾で立つ助詞の語も落とすので、後語を要る検査は無くなつた。 */
    expect(物.split("番 + 1 < 敬語を剥いだ語々.length").length - 1).toBe(0);
  });
});
