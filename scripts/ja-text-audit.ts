/**
 * 利用者に出る文に、現代仮名遣いでない字（旧字体）や中国語が混ざっていないかの**候補**を出す。
 *
 * 使い方:
 *   node scripts/ja-text-audit.ts                # 既定のファイルを見る
 *   node scripts/ja-text-audit.ts site/app.ts    # 指定したファイルだけを見る
 *
 * 何故「候補」か: 註や識別子では旧字体を使う（この計画の内側の文体）。出口は常に 0（検査では
 * ない – 赤くして止める物ではない。止める物は tests/ 側に在る）。
 *
 * 目安は三つ（**掃除してよいのは「文らしい」だけ**）:
 *   - コードらしい: 行から註を外した残りが代入・`名前: "…"`・宣言で始まる、又は行に閉じない
 *     `${…}` が在る。此の計画は日本語の識別子を使ふので、字の掃除は**改名**に化ける。
 *   - 鍵らしい: 語の表（`words:`・寄せ表）の中の短い文字列。旧字体で打つ人の為に**意図的に**
 *     置いてある（第 772 回に一括置換で検査七本が落ちた）。
 *   - 文らしい: 上の何れでもない物＝利用者に出る文。掃除の対象。
 *
 * 此の三つに分けるまでに五度失敗した（第 772・774・775・777・779 回）。誤檢知の內譯は
 * ①畳み表の鍵（`錄: "録",`）②註の末尾③コード中の識別子（`皆當 = false;`・`${…}` の中）。
 * **少しずつ直し、直すたびに型檢查と全檢查を回す**のが此の計畫で判つた安全な進め方。
 *
 * 註は先に外してから探す（第 776 回）。外さずに數へると、註の字まで「文らしい」に成つて
 * 件數が 4 倍に膨れた（第 781 回に實測 – 469 件）。
 */

import { readFileSync } from "node:fs";

/** 中国語の語（日本語では別の語を使う）。 */
const 中国語の語 = ["文件", "快照", "檔案", "值", "增"];

/** 旧字体の字（この計画の内側では使うが、利用者に出る文では使わない）。 */
const 旧字体の字 = "收錄檢當兩變學會國轉譯聲眞晝驛拂";

/** 計画の内側の名前（変数名・関数名）に使っている字。利用者に出ないので報告から外す。
 * 實測 2026-10-06: 既定の五ファイルで 75 件のうち大半が `聲`（読み上げの函数名）だつた。 */
const 計畫の內側の名 = ["聲"];

const 既定のファイル = [
  "site/app.ts",
  "site/template.html",
  "site/recommender.ts",
  "src/build.ts",
  "src/mcp.ts",
];

type 目安 = "コードらしい" | "鍵らしい" | "文らしい";

/** 註（塊と行）を外す。完全ではない（文字列の中の記号に弱い）が、候補を出すには足りる。
 * 行の數が變はらぬ樣、外した所は空白で埋める（行番號がずれん）。 */
function 註を外す(本文: string): string {
  return 本文
    .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "))
    .replace(/(?<=\/\/)[^\n]*/g, (m) => m.replace(/[^\n]/g, " "));
}

/** 行の見た目から目安を決める（第 773・780 回）。 */
function 目安を決める(行: string): 目安 {
  const 註を外した行 = 行.replace(/\/\/.*$/, "").trim();
  if (
    /\$\{[^}]*$/.test(行) ||
    /^[^\s"'`(,]+\s*=[^=]/.test(註を外した行) ||
    /^[^\s"'`(,]+\s*:\s*["'`]/.test(註を外した行) ||
    /^(?:const|let|var|function|class|interface|type|return|if|for|while|import|export)\b/.test(
      註を外した行,
    )
  ) {
    return "コードらしい";
  }
  if (/^\s*["'`][^"'`]*["'`],?\s*$/.test(行) || /words:|\[\s*$|寄せ|\bretype\b/.test(行)) {
    return "鍵らしい";
  }
  return "文らしい";
}

const 數: Record<目安, number> = { コードらしい: 0, 鍵らしい: 0, 文らしい: 0 };
const 文だけ = process.argv.includes("--文");
const 引數 = process.argv.slice(2).filter((a) => !a.startsWith("--"));

function 見る(path: string): void {
  const 本文 = readFileSync(path, "utf8");
  const 註抜き = 註を外す(本文);
  const 行々 = 本文.split("\n");
  const 言ふ = (位置: number, 見出し: string): void => {
    const 行番号 = 註抜き.slice(0, 位置).split("\n").length;
    const 行 = (行々[行番号 - 1] ?? "").trim();
    const 目安 = 目安を決める(行);
    數[目安] += 1;
    if (!文だけ || 目安 === "文らしい") {
      console.log(`${path}:${行番号}: ${見出し}（${目安}） | ${行.slice(0, 78)}`);
    }
  };
  for (const 語 of 中国語の語) {
    let at = 註抜き.indexOf(語);
    while (at >= 0) {
      言ふ(at, `中国語「${語}」`);
      at = 註抜き.indexOf(語, at + 1);
    }
  }
  for (const 字 of 旧字体の字) {
    if (計畫の內側の名.includes(字)) continue;
    let at = 註抜き.indexOf(字);
    while (at >= 0) {
      言ふ(at, `旧字体「${字}」`);
      at = 註抜き.indexOf(字, at + 1);
    }
  }
}

for (const path of 引數.length ? 引數 : 既定のファイル) {
  try {
    見る(path);
  } catch (error) {
    console.log(`${path}: 讀めない（${String(error).slice(0, 70)}）`);
  }
}
const 合計 = 數["コードらしい"] + 數["鍵らしい"] + 數["文らしい"];
console.log(
  `\n候補 ${合計} 件（コードらしい ${數["コードらしい"]} 件・鍵らしい ${數["鍵らしい"]} 件・` +
    `文らしい ${數["文らしい"]} 件）。**掃除してよいのは文らしい物だけ** – 鍵は旧字体で打つ人の` +
    `為に意図的に置いてあり（第 772 回）、コードは改名に化ける（第 774 回）。`,
);
