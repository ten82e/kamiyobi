/** 中國語の入力を**その_receive する**行 – 檢査が入れては居ない（第 915 回の續け）。
 * `site/recommender.ts` の 2 行が此れで、`个月前` の樣な中國語の打鍵を拾ふ正規表現と、
 * `并べ替え` の樣な打鍵表。**，故意に受ける**物なので直してはならない。 */
/** この行は中國語をわざと受ける物か（中國語の打鍵の正規表現・打鍵表）。
 * 內容で決める – 行番号は註を外す前の數え方であり、外すとすぐずれる。 */
function 中國語を受ける行か(行: string): boolean {
  return /[\u4e00-\u9fff]/.test(行) && (行.includes("/") || 行.includes("[") || 行.includes(":"));
}

